"""Generate src/cvc5_mojo/enums.mojo from the cvc5 C headers.

The numeric values are not computed by parsing. The enumerator names are
collected from the headers; a small C program that prints the value of
every enumerator is compiled against the same headers and run. This stays
correct whatever values cvc5 assigns.

Usage: python -m bindgen.enums
"""

import os
import re
import sys

from . import c_headers, config

HEADERS = [
    "cvc5/cvc5_kind.h",
    "cvc5/cvc5_types.h",
    "cvc5/cvc5_proof_rule.h",
    "cvc5/cvc5_skolem_id.h",
]

DEFINE_RE = re.compile(r"#define\s+EVALUE\(name\)\s+(CVC5_[A-Z0-9_]*)##name")
ENUM_RE = re.compile(r"^\s*enum\s+ENUM\((\w+)\)")
ENTRY_RE = re.compile(r"EVALUE\(\s*(\w+)")


def collect_documented(include_dir):
    """Return [(enum_name, c_prefix, {entry: header comment})] in header order."""
    enums = []
    for rel in HEADERS:
        path = os.path.join(include_dir, rel)
        prefix = None
        current = None
        comment = []
        in_comment = False
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                if line.lstrip().startswith("/**"):
                    comment = []
                    in_comment = True
                    line = line.split("/**", 1)[1]
                if in_comment:
                    end = "*/" in line
                    body = line.split("*/", 1)[0]
                    comment.append(re.sub(r"^\s*\* ?", "", body).rstrip())
                    in_comment = not end
                    continue
                m = DEFINE_RE.search(line)
                if m:
                    prefix = m.group(1)
                    continue
                m = ENUM_RE.match(line)
                if m:
                    if prefix is None:
                        sys.exit(f"{rel}: enum {m.group(1)} without a C prefix")
                    current = (m.group(1), prefix, {})
                    comment = []
                    continue
                if current is not None:
                    if line.strip().startswith("};"):
                        enums.append(current)
                        current = None
                        continue
                    m = ENTRY_RE.search(line)
                    if m and not line.lstrip().startswith(("*", "/*", "//")):
                        current[2][m.group(1)] = "\n".join(comment).strip()
                        comment = []
    return enums


def collect(include_dir):
    """Return [(enum_name, c_prefix, [entry names])] in header order."""
    return [(name, prefix, list(entries))
            for name, prefix, entries in collect_documented(include_dir)]


def documentation(include_dir=None):
    """Extract Kind contracts for the tutorial's operator reference."""
    return {name: entries for name, _, entries in
            collect_documented(str(include_dir or config.INCLUDE_DIR)) if name == "Kind"}


def dump_values(include_dir, enums, cc):
    """Compile and run a C program that prints every enumerator value."""
    lines = ["#include <stdio.h>", "int main(void) {"]
    for name, prefix, entries in enums:
        for entry in entries:
            lines.append(
                f'  printf("%s|%s|%lld\\n", "{name}", "{entry}", '
                f"(long long){prefix}{entry});"
            )
    lines += ["  return 0;", "}"]
    values = {}
    for row in c_headers.run_program(lines, "Enum value extraction", include_dir, cc).splitlines():
        enum, entry, value = row.split("|")
        values.setdefault(enum, []).append((entry, int(value)))
    return values


def values(include_dir=None, cc=None):
    """Return {enum: [(entry, value), ...]} for every cvc5 enum."""
    include_dir = str(include_dir or config.INCLUDE_DIR)
    return dump_values(include_dir, collect(include_dir), cc or config.c_compiler())


def emit_mojo(values, version):
    out = [
        f"# Generated by bindgen from the cvc5 {version} C headers. Do not edit.",
        "# Regenerate with `pixi run --locked generate`.",
        "",
        "from std.hashlib import Hasher",
        "",
    ]
    for enum, entries in values.items():
        out += [""] + emit_enum(enum, entries, f"The cvc5 `{enum}` (C enum `Cvc5{enum}`).")
    return "\n".join(out) + "\n"


def emit_enum(enum, entries, summary):
    """One enum struct: an `Int32` with a `comptime` member per entry, printed
    as Python prints its enums (`Kind.ADD`; `repr`: `<Kind.ADD: 20>`) and
    hashable like them."""
    out = [
        "@fieldwise_init",
        f"struct {enum}(ImplicitlyCopyable, Equatable, Hashable, Writable):",
        f'    """{summary}',
        "",
        f"    It prints as Python's enums do: `{enum}.{entries[0][0]}`, and its `repr`",
        f"    is `<{enum}.{entries[0][0]}: {entries[0][1]}>`.",
        '    """',
        "",
        "    var value: Int32",
        "",
    ]
    for entry, value in entries:
        out.append(f"    comptime {entry} = {enum}({value})")
    out += [""] + _name_table(enum, entries) + [
        "",
        "    def __eq__(self, other: Self) -> Bool:",
        "        return self.value == other.value",
        "",
        "    def __ne__(self, other: Self) -> Bool:",
        "        return self.value != other.value",
        "",
        "    def __hash__[H: Hasher](self, mut hasher: H):",
        "        self.value.__hash__(hasher)",
        "",
        "    def _name(self) -> StaticString:",
        '        """The member name, or "" for a value that names no member."""',
        "        var i = Int(self.value) - Self._FIRST",
        "        if i < 0 or i >= Self._COUNT:",
        '            return ""',
        "        var names = Self._NAMES",
        "        var start = 0",
        "        for _ in range(i):",
        '            start = names.find(" ", start) + 1',
        '        var end = names.find(" ", start)',
        "        return names[byte = start : end if end >= 0 else names.byte_length()]",
        "",
        "    def write_to(self, mut writer: Some[Writer]):",
        "        var name = self._name()",
        "        if name:",
        f'            writer.write("{enum}.", name)',
        "        else:",
        f'            writer.write("{enum}(", self.value, ")")',
        "",
        "    def write_repr_to(self, mut writer: Some[Writer]):",
        "        var name = self._name()",
        "        if name:",
        f'            writer.write("<{enum}.", name, ": ", self.value, ">")',
        "        else:",
        f'            writer.write("{enum}(", self.value, ")")',
    ]
    return out


def _name_table(enum, entries):
    """The member names in value order, for printing; the values must be
    contiguous, which the generator checks."""
    ordered = sorted(entries, key=lambda e: e[1])
    first = ordered[0][1]
    if [v for _, v in ordered] != list(range(first, first + len(ordered))):
        sys.exit(f"{enum}: values are not contiguous; printing needs another name table")
    return [f"    comptime _FIRST = {first}",
            f"    comptime _COUNT = {len(ordered)}",
            f'    comptime _NAMES: StaticString = "{" ".join(n for n, _ in ordered)}"']


def main():
    vals = values()
    config.ENUMS_FILE.write_text(emit_mojo(vals, config.pinned()["version"]))
    counts = ", ".join(f"{k}={len(v)}" for k, v in vals.items())
    print(f"wrote {config.ENUMS_FILE.relative_to(config.ROOT)}: {counts}")


if __name__ == "__main__":
    main()
