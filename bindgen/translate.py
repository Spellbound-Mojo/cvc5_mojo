def _module(source, docstring, not_run, used, helpers, typed, helper_lines, functions):
    """A generated module: the header, the imports, the helpers that the
    `functions` ([(Python function or None, Mojo lines)]) call, directly or
    through other helpers, then the functions."""
    called, todo = set(), [fn for fn, _ in functions if fn is not None]
    while todo:
        for n in ast.walk(todo.pop()):
            if isinstance(n, ast.Name) and n.id in typed and n.id not in called:
                called.add(n.id)
                todo.append(helpers[n.id])
    used = set(used).union(*(helper_lines[name][1] for name in called))
    support = sorted(u.removeprefix("support.") for u in used if u.startswith("support."))
    used -= {"support." + name for name in support}
    head = [f"{MARKER} from cvc5's {source}. Do not edit.", "# Regenerate with `pixi run --locked generate`."]
    if not_run:
        head += ["#", "# Not run here (see the coverage report):"] + [f"#   {line}" for line in not_run]
    head += [f'"""{docstring}"""', ""]
    math = sorted(u.removeprefix("std.math.") for u in used if u.startswith("std.math."))
    used -= {f"std.math.{f}" for f in math}
    std = (["from std.math import " + ", ".join(math)] if math else []) + (
        ["from std.testing import " + ", ".join(sorted(used & set(TESTING)))] if used & set(TESTING) else [])
    if "std.memory.ArcPointer" in used:
        std.append("from std.memory import ArcPointer")
        used.remove("std.memory.ArcPointer")
    head += std + ([""] if std else [])
    if used & set(NUMBERS):
        head.append("from apn_mojo import " + ", ".join(sorted(used & set(NUMBERS))))
    if used - set(TESTING) - set(NUMBERS):
        head.append("from cvc5_mojo import " + ", ".join(sorted(used - set(TESTING) - set(NUMBERS))))
    body = []
    for name in support:
        helper, *params = name.split(":")
        fields = dict(zip(("owner", "element"), params))
        fields["same"] = str(len(params) == 2 and params[0] == params[1])
        body += ["", ""] + SUPPORT[helper].format(**fields).rstrip().splitlines()
    for name in helpers:
        if name in called:
            body += ["", ""] + helper_lines[name][0]
    for _, lines in functions:
        body += ["", ""] + lines
    return "\n".join(head + body) + "\n"


EXAMPLE_DIR = "examples/api/python"


def _main_block(tree):
    """The body of `if __name__ == "__main__":`, or None."""
    for node in tree.body:
        if (isinstance(node, ast.If) and ast.unparse(node.test) in ('__name__ == "__main__"', "__name__ == '__main__'")):
            return node.body
    return None


def example_sources():
    """cvc5's Python examples: the scripts with a main block."""
    return [p for p in sorted((config.SOURCE_DIR / EXAMPLE_DIR).glob("*.py"))
            if _main_block(ast.parse(p.read_text(encoding="utf-8"))) is not None]


def example_name(path):
    """The name of an example's Mojo module and recorded output."""
    return path.stem.replace("-", "_")


class _Inline(ast.NodeTransformer):
    """`utils.f` as `f`: the functions of an imported example module become
    helpers of the example."""

    def __init__(self, modules):
        self.modules = modules

    def visit_Attribute(self, node):
        self.generic_visit(node)
        if isinstance(node.value, ast.Name) and node.value.id in self.modules:
            return ast.copy_location(ast.Name(id=node.attr, ctx=node.ctx), node)
        return node


def translate_example(path, api, compile_failure_line=None):
    """Translate one example script: its main block becomes Mojo's `main`, and
    its functions, with those of the example modules it imports (`import
    utils`), become helpers typed by their calls. Returns {"text": Mojo source
    or None, "not_translated": reason or None}."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    modules = {}
    for node in tree.body:
        if isinstance(node, ast.Import):
            for alias in node.names:
                local = path.parent / f"{alias.name}.py"
                if local.exists():
                    modules[alias.asname or alias.name] = ast.parse(local.read_text(encoding="utf-8"))
    tree = _Inline(set(modules)).visit(tree)
    helpers = {n.name: n for m in list(modules.values()) + [tree] for n in m.body if isinstance(n, ast.FunctionDef)}
    if "main" in helpers:
        class RenameMain(ast.NodeTransformer):
            def visit_Name(self, node):
                if node.id == "main":
                    node.id = "_example_main"
                return node

            def visit_FunctionDef(self, node):
                if node.name == "main":
                    node.name = "_example_main"
                return self.generic_visit(node)

        tree = RenameMain().visit(tree)
        helpers["_example_main"] = helpers.pop("main")
    main = ast.FunctionDef(name="main", args=ast.arguments(posonlyargs=[], args=[], kwonlyargs=[], kw_defaults=[],
                                                           defaults=[]),
                           body=_main_block(tree), decorator_list=[], type_params=[])
    not_translated = {}
    typed, helper_lines = _helpers(api, helpers, [main], {}, (), not_translated, compile_failure_line)
    missing = [n.id for n in ast.walk(main) if isinstance(n, ast.Name) and n.id in helpers and n.id not in typed]
    if missing:
        return {"text": None, "not_translated": f"calls `{missing[0]}`, not translated: {not_translated[missing[0]]}"}
    comparison = config.overrides().get("example_checks", {}).get(example_name(path), "exact")
    if comparison not in ("exact", "model"):
        raise SystemExit(f"unknown example comparison: {comparison}")
    t = Translator(api, {}, (), typed, model_check=comparison == "model")
    try:
        lines = t.test(main)
    except Untranslatable as e:
        return {"text": None, "not_translated": str(e)}
    text = _module(f"{EXAMPLE_DIR}/{path.name}", f"cvc5's Python example `{path.name}`, translated to Mojo.", [],
                   t.used, helpers, typed, helper_lines, [(main, lines)])
    rejections = sorted(t.rejections | set().union(*(entry[2] for entry in helper_lines.values())))
    return {"text": text, "not_translated": None, "model_output": t.model_output, "rejections": rejections}


