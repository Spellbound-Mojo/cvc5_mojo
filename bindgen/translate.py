# Python builtins and their Mojo counterparts.
BUILTINS = {"str": "String", "int": "Int", "len": "len", "range": "range", "hash": "hash",
            "print": "print", "repr": "repr", "Fraction": "Rational", "abs": "abs"}
# Python's math functions that std.math has, for floats.
MATH = ("ceil", "floor", "sqrt", "exp", "log")
# The result types of Python builtins.
BUILTIN_RESULTS = {"str": "String", "repr": "String", "int": "Int", "len": "Int"}
OPS = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*", ast.FloorDiv: "//", ast.Mod: "%", ast.Pow: "**",
       ast.Eq: "==", ast.NotEq: "!=", ast.Lt: "<", ast.LtE: "<=", ast.Gt: ">", ast.GtE: ">=",
       ast.In: "in", ast.NotIn: "not in",
       ast.And: "and", ast.Or: "or", ast.BitAnd: "&", ast.BitOr: "|", ast.LShift: "<<", ast.RShift: ">>"}


class Untranslatable(Exception):
    """A construct the translator does not handle; the message is the reason."""


def _mentions(node, name):
    return any(isinstance(n, ast.Name) and n.id == name for n in ast.walk(node))


def _yields_target(comprehension):
    """Whether a one-generator comprehension yields its loop target unchanged,
    as in `[x for x in xs]`. Compared as source: `ast.dump` omits the default
    load context from Python 3.15, so its output depends on the version."""
    return ast.unparse(comprehension.elt) == ast.unparse(comprehension.generators[0].target)


def _read_first(name, stmts):
    """Whether `stmts`, in order, read `name` before assigning it; None if
    they do not mention it."""
    for s in stmts:
        if isinstance(s, ast.Assign):
            if _mentions(s.value, name):
                return True
            if any(_mentions(t, name) for t in s.targets):
                return False
        elif isinstance(s, (ast.If, ast.While, ast.For, ast.With)):
            heads = ([s.test] if isinstance(s, (ast.If, ast.While)) else [s.iter] if isinstance(s, ast.For)
                     else [i.context_expr for i in s.items])
            if any(_mentions(h, name) for h in heads):
                return True
            found = _read_first(name, s.body)
            if found is not None:
                return found
        elif _mentions(s, name):
            return True
    return None


def _string(value):
    return json.dumps(value, ensure_ascii=False)


def _integer_constant(node):
    """An integer-only constant expression, before Mojo infers a machine Int."""
    if isinstance(node, ast.Constant) and type(node.value) is int:
        return node.value
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        n = _integer_constant(node.operand)
        return -n if n is not None else None
    if isinstance(node, ast.BinOp):
        a, b = _integer_constant(node.left), _integer_constant(node.right)
        if a is not None and b is not None:
            if isinstance(node.op, ast.Add):
                return a + b
            if isinstance(node.op, ast.Sub):
                return a - b
            if isinstance(node.op, ast.Mult):
                return a * b
            if isinstance(node.op, ast.Pow) and 0 <= b <= 4096:
                return a ** b
    return None


class Api:
    """What the translation needs to know about the Mojo bindings."""

    def __init__(self, snap):
        self.exported = exported_names(snap)
        self.unmirrored = unmirrored_methods(snap)
        self.delegated = delegated_methods(snap)
        self.results = result_types(snap)
        self.params = parameter_types(snap)
        self.variadics = parameter_types(snap, variadic=True)
        model, _ = gen_api.generated(snap)
        self.owners = set(model.owners)
        self.fields = {}
        self.plugins = {}
        self.plugin_init = snap["python"]["Plugin"]["init"]
        for fragment in model.manual.values():
            cls, aliases = None, {}
            for line in fragment.get("extra", []):
                if m := gen_api.STRUCT_RE.match(line):
                    cls, aliases = m[1], {}
                elif cls and (m := re.match(r"    comptime (\w+) = (.+)$", line)):
                    aliases[m[1]] = m[2]
                elif cls and (m := re.match(r"    var (\w+): (.+)$", line)):
                    kind = m[2]
                    for name, value in aliases.items():
                        kind = kind.replace("Self." + name, value)
                    self.fields[cls, m[1]] = kind
        # Python's objects are true unless their class defines `__bool__` or `__len__`.
        self.always_true = {cls for cls, info in snap["python"].items()
                            if not {"__bool__", "__len__"} & set(info["methods"])}

    def param(self, cls, method, position, arity, lists=False):
        """The Mojo type of a method's parameter at `position`, if every
        overload taking `arity` arguments (and a list there, with `lists`)
        agrees on it."""
        found = {ps[position] for ps in self.params.get((cls, method), ())
                 if position < len(ps) and len(ps) >= arity and (not lists or ps[position].startswith("List["))}
        return found.pop() if len(found) == 1 else None


class Translator:
    """Translates one test or helper function of a module."""

    def __init__(self, api, fixtures, null_contexts=(), helpers=None, compile_failure_line=None, model_check=False):
        self.api = api
        self.exported = api.exported
        self.unmirrored = api.unmirrored
        self.delegated = api.delegated
        self.helpers = helpers or {}  # name -> (parameter types, return type or None)
        self.helper_calls = {}  # helper -> [argument types], at each call
        self.types = {}  # variable -> Mojo type, where it can be inferred
        self.names = {}  # variable -> its Mojo name, after a rebinding to another type
        self.reassigned = set()  # variables assigned after their declaration
        self.following = []  # the statements after the current one, in its block
        self.fixtures = fixtures
        self.null_contexts = set(null_contexts)
        self.declared = set()
        self.counter = 0
        self.used = set()
        self.probing = False  # a first pass that only infers the variables' types
        self.compile_failure_line = compile_failure_line
        self.rejections = set()
        self.literal_lengths = {}
        self.model_check = model_check
        self.model_values = set()
        self.model_output = []

    # -- expressions -----------------------------------------------------

    def expr(self, node):
        method = getattr(self, "e_" + type(node).__name__, None)
        if method is None:
            raise Untranslatable(f"{type(node).__name__} expression `{ast.unparse(node)}`")
        return method(node)

    def e_Constant(self, node):
        v = node.value
        if v is None:
            return "None"
        if isinstance(v, bool):
            return "True" if v else "False"
        if isinstance(v, int):
            return str(v)
        if isinstance(v, str):
            return _string(v)
        if isinstance(v, float):
            return repr(v)
        raise Untranslatable(f"constant `{v!r}`")

    def e_Name(self, node):
        name = node.id
        if name in self.exported:
            self.used.add(name)
        elif name in BUILTINS:
            if name == "Fraction":
                self.used.add("Rational")
            return BUILTINS[name]
        elif name not in self.declared and name not in self.helpers and name not in self.api.plugins:
            raise Untranslatable(f"`{name}` has no Mojo counterpart")
        return self.names.get(name, name)

    def e_Attribute(self, node):
        if isinstance(node.value, ast.Name) and node.value.id == "cvc5":
            if node.attr not in self.exported:
                raise Untranslatable(f"`cvc5.{node.attr}` has no Mojo counterpart")
            self.used.add(node.attr)
            return node.attr
        value = self.expr(node.value)
        if (self.type_of(node.value) or "").startswith("ArcPointer["):
            value += "[]"
        return f"{value}.{node.attr}"

    def e_Call(self, node):
        if isinstance(node.func, ast.Name) and node.func.id in self.api.plugins:
            if node.keywords:
                raise Untranslatable("plugin constructors require positional arguments")
            self.used.add("std.memory.ArcPointer")
            return f"ArcPointer({node.func.id}({', '.join(self.expr(a) for a in node.args)}))"
        if self.model_check and isinstance(node.func, ast.Attribute) and self.type_of(node.func.value) == "Solver":
            method = node.func.attr
            if method in ("checkSat", "getValue"):
                self.used |= {"support.model", "Solver", "Result", "Term", "Kind", "assert_true"}
                args = [self.expr(node.func.value)] + [self.expr(a) for a in node.args]
                return f"{'_checked_sat' if method == 'checkSat' else '_checked_value'}({', '.join(args)})"
        if isinstance(node.func, ast.Name) and node.func.id == "isinstance":
            if len(node.args) == 2 and self.type_of(node.args[0]) and ast.unparse(node.args[1]) in self.exported:
                actual, expected = self.type_of(node.args[0]), ast.unparse(node.args[1])
                self.used |= {f"support.isinstance:{actual}:{expected}", actual}
                return f"_isinstance_{actual}_{expected}({self.expr(node.args[0])})"
            raise Untranslatable("`isinstance` with an unknown type")
        if ast.unparse(node.func) == "Fraction" and len(node.args) == 1 and isinstance(node.args[0], ast.Constant):
            # Fraction(float) means the exact binary float, not its decimal spelling.
            value = node.args[0].value
            if isinstance(value, (float, str)):
                value = Fraction(value)
                self.used.add("Rational")
                return f"Rational({value.numerator}, {value.denominator})"
        if ast.unparse(node.func) == "isnan" and len(node.args) == 1:
            self.used.add("std.math.isnan")
            return f"isnan({self.as_type(node.args[0], 'Float64')})"
        if isinstance(node.func, ast.Attribute) and node.func.attr in self.unmirrored:
            raise Untranslatable(f"`{node.func.attr}` is not mirrored: {self.unmirrored[node.func.attr]}")
        if isinstance(node.func, ast.Name) and node.func.id in self.helpers:
            self.helper_calls.setdefault(node.func.id, []).append([self.type_of(a) for a in node.args])
        if (isinstance(node.func, ast.Attribute) and node.func.attr == "format"
                and isinstance(node.func.value, ast.Constant) and isinstance(node.func.value.value, str)):
            return self._format(node)
        if (isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Name)
                and node.func.value.id == "math" and node.func.attr in MATH and not node.keywords):
            return self._math(node)
        if ast.unparse(node.func) == "len" and len(node.args) == 1 and self.type_of(node.args[0]) == "String":
            return f"{self.expr(node.args[0])}.count_codepoints()"  # Python counts code points
        func = self.expr(node.func)
        if isinstance(node.func, ast.Attribute) and self.type_of(node.func.value) in self.delegated:
            # A deprecated method that Python implements as `self.tm.<method>(...)`.
            targets = self.delegated[self.type_of(node.func.value)]
            if node.func.attr in targets:
                owner, method = targets[node.func.attr]
                func = f"{self.expr(node.func.value)}.get{owner}().{method}"
        owner = self.type_of(node.func.value) if isinstance(node.func, ast.Attribute) else None
        args = []
        for i, a in enumerate(node.args):
            if isinstance(a, ast.Starred):
                continue
            expected = self.api.param(owner, node.func.attr, i, len(node.args), lists=True) if owner else None
            variadics = self.api.variadics.get((owner, node.func.attr), set()) if owner else set()
            accepts = {ps[i] for ps in self.api.params.get((owner, node.func.attr), ()) if i < len(ps)} if owner else set()
            if expected and self._list_of(a) == expected and self.type_of(a) not in accepts | variadics:
                args.append(self.collect(a))
            else:
                args.append(self.argument(a, owner))
        if any(isinstance(a, ast.Starred) for a in node.args):
            args.append(self._unpacked(node))
        args += [f"{k.arg}={self.expr(k.value)}" for k in node.keywords if k.arg]
        return f"{func}({', '.join(args)})"

    def argument(self, node, owner=None):
        """A call argument of a method of `owner`. Python iterates a set or a
        dict passed where the bindings take a list; with at most one element,
        its order is the list's."""
        if isinstance(node, ast.Dict) and not node.keys:
            return "[]"
        if isinstance(node, ast.Set) and len(node.elts) == 1:
            return f"[{self.expr(node.elts[0])}]"
        if (owner or "").startswith("List["):
            return self._copied(node)  # a list's methods take ownership of a list argument
        return self.expr(node)

    def _copied(self, node):
        """`node`, copied if it names a list: a Mojo list is not implicitly
        copied, where Python would share it."""
        text = self.expr(node)
        if isinstance(node, ast.Name) and (self.type_of(node) or "").startswith("List["):
            return f"{text}.copy()"
        return text

    def _unpacked(self, call):
        """`f(a, *xs)`: Mojo cannot unpack a list into arguments, but where
        Python's method takes `*args`, the bindings also take a `List`."""
        star = call.args[-1]
        if (not isinstance(star, ast.Starred) or sum(isinstance(a, ast.Starred) for a in call.args) != 1
                or not isinstance(call.func, ast.Attribute)):
            raise Untranslatable(f"argument unpacking in `{ast.unparse(call)}`")
        position, kind = len(call.args) - 1, self.type_of(star.value)
        lists = {ps[position] for ps in self.api.params.get((self.type_of(call.func.value), call.func.attr), ())
                 if len(ps) == position + 1 and ps[position].startswith("List[")}
        if kind and kind.startswith("List[Tuple["):
            # Use the existing variadic overload with a statically sized tuple.
            # The list itself still gets evaluated and indexed at run time.
            value = star.value
            if isinstance(value, ast.Name) and value.id in self.literal_lengths:
                return ", ".join(f"{self.expr(value)}[{i}]" for i in range(self.literal_lengths[value.id]))
        if kind is None or kind not in lists:
            raise Untranslatable(f"argument unpacking in `{ast.unparse(call)}`")
        return self.expr(star.value)

    def type_of(self, node):
        """The Mojo type of `node` where it can be inferred, else None: from a
        constructor call, a literal, a method's generated signature, a helper's
        return type or a list element."""
        if isinstance(node, ast.Name):
            return self.types.get(node.id)
        if isinstance(node, ast.Attribute):
            return self.api.fields.get((self.type_of(node.value), node.attr))
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            return self.type_of(node.operand)
        if isinstance(node, ast.Constant):
            return {str: "String", bool: "Bool", int: "Int", float: "Float64"}.get(type(node.value))
        if isinstance(node, ast.Tuple):
            kinds = [self.type_of(e) for e in node.elts]
            return "Tuple[" + ", ".join(kinds) + "]" if all(kinds) else None
        if isinstance(node, ast.Dict) and node.keys:
            kinds = self.type_of(node.keys[0]), self.type_of(node.values[0])
            return "Dict[" + ", ".join(kinds) + "]" if all(kinds) else None
        if isinstance(node, ast.ListComp) and len(node.generators) == 1 and _yields_target(node):
            return self._list_of(node.generators[0].iter)
        if isinstance(node, ast.List) and node.elts and self.type_of(node.elts[0]):
            return f"List[{self.type_of(node.elts[0])}]"
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
            if "String" in (self.type_of(node.left), self.type_of(node.right)):
                return "String"
        if isinstance(node, ast.JoinedStr):
            return "String"
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in BUILTIN_RESULTS:
            return BUILTIN_RESULTS[node.func.id]
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                and ast.unparse(node.func.value) == "math" and node.func.attr in MATH):
            return "Float64"
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "format"
                and isinstance(node.func.value, ast.Constant) and isinstance(node.func.value.value, str)):
            return "String"
        if isinstance(node, ast.Subscript) and not isinstance(node.slice, ast.Slice):
            container = self.type_of(node.value)
            if isinstance(node.slice, ast.Constant) and (container, node.slice.value) in self.api.fields:
                return self.api.fields[container, node.slice.value]
            if container and container.startswith("Dict["):
                return reference._split(container[5:-1])[1]
            if container and container.startswith("Tuple[") and isinstance(node.slice, ast.Constant):
                return reference._split(container[6:-1])[node.slice.value]
            if container and container.startswith("List[") and container.endswith("]"):
                return container[5:-1]
            found = self.api.results.get((container, "__getitem__"), set())
            return next(iter(found)) if len(found) == 1 else None
        if isinstance(node, ast.Call):
            name = ast.unparse(node.func).removeprefix("cvc5.")
            if name in self.api.plugins:
                return f"ArcPointer[{name}]"
            if name in self.exported:
                return name
            if name in self.helpers:
                return self.helpers[name][1]
            if isinstance(node.func, ast.Attribute):
                found = self.api.results.get((self.type_of(node.func.value), node.func.attr), set())
                return next(iter(found)) if len(found) == 1 else None
        return None

    def e_JoinedStr(self, node):
        # f"a{x}b": Python formats each value with str(), as Mojo's String(...) writes it.
        parts = []
        pattern = []
        model = False
        for v in node.values:
            if isinstance(v, ast.Constant):
                parts.append(_string(v.value))
                pattern.append(re.escape(v.value))
            elif v.format_spec is not None or v.conversion not in (-1, ord("s"), ord("r")):
                raise Untranslatable(f"formatted value in `{ast.unparse(node)}`")
            else:
                text = self.expr(v.value)
                parts.append(f"repr({text})" if v.conversion == ord("r") else text)
                if self.model_check:
                    if not self.is_model_value(v.value):
                        raise Untranslatable("model output mixes model values with other interpolation")
                    model = True
                    pattern.append("(.+)")
        if model:
            self.model_output.append("".join(pattern))
        return f"String({', '.join(parts)})"

    def is_model_value(self, node):
        return ((isinstance(node, ast.Name) and node.id in self.model_values)
                or (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                    and node.func.attr == "getValue" and self.type_of(node.func.value) == "Solver"))

    def _format(self, node):
        """`"a {} b".format(x)`, with positional fields only, as `String("a ", x, " b")`."""
        template = node.func.value.value
        args = [self.expr(a) for a in node.args]
        if node.keywords or any(isinstance(a, ast.Starred) for a in node.args):
            raise Untranslatable(f"`{ast.unparse(node)}`")
        parts, auto = [], 0
        for literal, field, spec, conversion in string.Formatter().parse(template):
            if literal:
                parts.append(_string(literal))
            if field is None:
                continue
            if spec or conversion or not (field == "" or field.isdigit()):
                raise Untranslatable(f"format field `{{{field}}}` in `{ast.unparse(node)}`")
            index = auto if field == "" else int(field)
            auto += field == ""
            parts.append(args[index])
        return f"String({', '.join(parts)})"

    def _math(self, node):
        """`math.f(x)` on floats, from std.math; `math.log(x, b)` is
        `log(x) / log(b)`, as Python computes it."""
        f = node.func.attr
        args = [f"Float64({self.expr(a)})" for a in node.args]
        if len(args) == 2 and f == "log":
            self.used.add("std.math.log")
            return f"(log({args[0]}) / log({args[1]}))"
        if len(args) != 1:
            raise Untranslatable(f"`{ast.unparse(node)}`")
        self.used.add(f"std.math.{f}")
        return f"{f}({args[0]})"

    def e_List(self, node):
        # Mojo infers an empty list's type from the parameter it is passed to.
        return "[" + ", ".join(self.expr(e) for e in node.elts) + "]"

    def collect(self, node):
        kind = self._list_of(node)
        if not kind:
            raise Untranslatable(f"iteration of `{ast.unparse(node)}` has no known element type")
        owner = self.type_of(node)
        if owner.startswith("List["):
            return f"{self.expr(node)}.copy()"
        if owner not in self.exported:
            raise Untranslatable(f"collection owner `{owner}`")
        self.used |= {f"support.collect:{owner}:{kind[5:-1]}"} | self._type_names(kind) | self._type_names(owner)
        return f"_collect_{owner}({self.expr(node)})"

    def e_ListComp(self, node):
        if len(node.generators) == 1:
            g = node.generators[0]
            if not g.ifs and not g.is_async and _yields_target(node):
                return self.collect(g.iter)
        raise Untranslatable(f"list comprehension `{ast.unparse(node)}`")

    def e_Dict(self, node):
        if not node.keys or any(k is None for k in node.keys):
            raise Untranslatable("dictionary literal without known key and value types")
        return "{" + ", ".join(f"{self.expr(k)}: {self.expr(v)}" for k, v in zip(node.keys, node.values)) + "}"

    def e_Tuple(self, node):
        return "(" + ", ".join(self.expr(e) for e in node.elts) + ("," if len(node.elts) == 1 else "") + ")"

    def e_Subscript(self, node):
        if isinstance(node.slice, ast.Slice):
            if node.slice.step is not None:
                raise Untranslatable(f"slice step in `{ast.unparse(node)}`")
            self.used.add("support.slice")
            start = self.expr(node.slice.lower) if node.slice.lower else "0"
            stop = self.expr(node.slice.upper) if node.slice.upper else "Int.MAX"
            return f"_slice({self.as_type(node.value, 'String')}, {start}, {stop})"
        if isinstance(node.slice, ast.Constant) and (self.type_of(node.value), node.slice.value) in self.api.fields:
            return f"{self.expr(node.value)}.{node.slice.value}"
        return f"{self.expr(node.value)}[{self.expr(node.slice)}]"

    def as_type(self, node, expected):
        text, kind = self.expr(node), self.type_of(node) or ""
        if kind.startswith("Optional["):
            text, kind = text + ".value()", kind[9:-1]
        if kind.startswith("Variant["):
            arms = reference._split(kind[8:-1])
            if expected not in arms:
                raise Untranslatable(f"{kind} cannot hold {expected}")
            text += f"[{expected}]"
        return text

    def e_UnaryOp(self, node):
        if isinstance(node.op, ast.Not):
            return f"not {self.condition(node.operand)}"
        if isinstance(node.op, ast.USub):
            return f"-{self.expr(node.operand)}"
        raise Untranslatable(f"operator in `{ast.unparse(node)}`")

    def e_BinOp(self, node):
        op = OPS.get(type(node.op))
        if op is None:
            raise Untranslatable(f"operator in `{ast.unparse(node)}`")
        return f"({self.expr(node.left)} {op} {self.expr(node.right)})"

    def e_BoolOp(self, node):
        op = OPS[type(node.op)]
        return "(" + f" {op} ".join(self.expr(v) for v in node.values) + ")"

    def e_Compare(self, node):
        if len(node.ops) != 1:
            raise Untranslatable(f"chained comparison `{ast.unparse(node)}`")
        op, right = node.ops[0], node.comparators[0]
        left_type = self.type_of(node.left) or ""
        # Python exposes typed metadata as dictionaries; compare every supplied field.
        if isinstance(right, ast.Dict) and any(cls == left_type for cls, _ in self.api.fields):
            if {k.value for k in right.keys if isinstance(k, ast.Constant)} != {field for cls, field in self.api.fields if cls == left_type}:
                raise Untranslatable("metadata equality requires all fields")
            if not isinstance(op, (ast.Eq, ast.NotEq)):
                raise Untranslatable("ordered comparison of metadata")
            parts = [self.e_Compare(ast.Compare(
                left=ast.Subscript(value=node.left, slice=k, ctx=ast.Load()),
                ops=[ast.Eq()], comparators=[v])) for k, v in zip(right.keys, right.values)]
            text = "(" + " and ".join(parts) + ")"
            return "not " + text if isinstance(op, ast.NotEq) else text
        if isinstance(right, ast.Dict) and not right.keys and left_type.startswith("Dict["):
            return f"(len({self.expr(node.left)}) {OPS[type(op)]} 0)"
        if isinstance(node.left, ast.Call) and ast.unparse(node.left.func) == "set" and len(node.left.args) == 1:
            kind = self._list_of(right)
            if not kind or not isinstance(op, (ast.Eq, ast.NotEq)):
                raise Untranslatable("set comparison without a known element type")
            self.used.add("support.set_equal")
            self.used |= self._type_names(kind)
            text = f"_set_equal[{kind[5:-1]}]({self.expr(node.left.args[0])}, {self.expr(right)})"
            return "not " + text if isinstance(op, ast.NotEq) else text
        if isinstance(op, (ast.Is, ast.IsNot)):
            negate = isinstance(op, ast.IsNot)
            if isinstance(right, ast.Constant) and right.value is None and left_type.startswith("Optional["):
                return ("" if negate else "not ") + f"Bool({self.expr(node.left)})"
            if isinstance(right, ast.Name) and right.id in ("bool", "int", "float", "str") and left_type == "Optional[String]":
                return f"({self.expr(node.left)}.value() {'!=' if negate else '=='} {_string(right.id)})"
            if left_type in self.api.owners and self.type_of(right) == left_type:
                return f"({self.expr(node.left)}._handle().ptr {'!=' if negate else '=='} {self.expr(right)}._handle().ptr)"
        if isinstance(op, (ast.In, ast.NotIn)):
            right_type = self.type_of(right)
            iterable = self._list_of(right)
            if iterable and iterable.startswith("List[Tuple[") and not right_type.startswith("List["):
                self.used |= {f"support.contains_key:{right_type}"} | self._type_names(right_type)
                text = f"_contains_key_{right_type}({self.expr(right)}, {self.expr(node.left)})"
                return "not " + text if isinstance(op, ast.NotIn) else text
            if isinstance(node.left, ast.Constant) and isinstance(node.left.value, bytes) and right_type == "String":
                # The bindings decode the native UTF-8 string; compare the same bytes as text.
                text = _string(node.left.value.decode("utf-8"))
                return f"({text} {OPS[type(op)]} {self.expr(right)})"
        if left_type.startswith(("Optional[", "Variant[")) and not isinstance(op, (ast.Is, ast.IsNot)):
            if isinstance(op, ast.NotEq):
                return "not " + self.e_Compare(ast.Compare(left=node.left, ops=[ast.Eq()], comparators=[right]))
            kind = self.type_of(right)
            if kind and kind.startswith("Dict["):
                arms = left_type.removeprefix("Variant[").removesuffix("]")
                compatible = [a for a in reference._split(arms) if a.startswith("Dict[")]
                if len(compatible) == 1:
                    kind = compatible[0]
            if kind:
                value, arms, guards = self.expr(node.left), left_type, []
                if arms.startswith("Optional["):
                    guards.append(f"Bool({value})")
                    value, arms = value + ".value()", arms[9:-1]
                if arms.startswith("Variant["):
                    choices = [kind]
                    if kind == "Int" and "UInt64" in reference._split(arms[8:-1]):
                        choices.append("UInt64")
                    tests = [f"({value}.isa[{ty}]() and ({value}[{ty}] {OPS[type(op)]} {self.expr(right)}))" for ty in choices]
                    guards.append("(" + " or ".join(tests) + ")")
                else:
                    guards.append(f"({value} {OPS[type(op)]} {self.expr(right)})")
                return "(" + " and ".join(guards) + ")"
        swap = {ast.Eq: ast.Eq, ast.NotEq: ast.NotEq, ast.Lt: ast.Gt, ast.Gt: ast.Lt, ast.LtE: ast.GtE, ast.GtE: ast.LtE}
        literal = (ast.Constant, ast.List)
        numbers = ("Integer", "Rational")
        if type(op) in swap and (
                (isinstance(node.left, literal) and not isinstance(right, literal))
                or (self.type_of(right) in numbers and self.type_of(node.left) not in numbers)):
            # `5 == x` as `x == 5`: a literal has no comparison with library types, and
            # a list literal on the left is a fixed-size `Array`; apn_mojo's numbers
            # compare with an `Int` on the right.
            node = ast.Compare(left=right, ops=[swap[type(op)]()], comparators=[node.left])
            op, right = node.ops[0], node.comparators[0]
        left = self.expr(node.left)
        if self.type_of(node.left) == "Rational" and self.type_of(right) == "Int":
            self.used.add("Rational")
            return f"({left} {OPS[type(op)]} Rational({self.expr(right)}))"  # a `Rational` compares with one
        if isinstance(op, (ast.Is, ast.IsNot)) and isinstance(right, ast.Constant) and isinstance(right.value, bool):
            return f"({left} {'==' if isinstance(op, ast.Is) else '!='} {self.e_Constant(right)})"
        if type(op) not in OPS:
            raise Untranslatable(f"comparison `{ast.unparse(node)}`")
        return f"({left} {OPS[type(op)]} {self.expr(right)})"

    # -- statements --------------------------------------------------------

    def block(self, stmts, indent):
        out = []
        for i, s in enumerate(stmts):
            self.following = stmts[i + 1 :]
            out += self.stmt(s, indent)
        return out or [indent + "pass"]

    def _empty_list(self, name, indent):
        """`x = []`: Mojo needs the element type. A later assignment in the
        same block declares `x`; else the type comes from the first later use
        that tells it: `x.append(e)`, or `x` passed where a method takes a list."""
        for later in self.following:
            if any(isinstance(n, ast.Name) and n.id == name for n in ast.walk(later)):
                if (isinstance(later, ast.Assign) and len(later.targets) == 1
                        and isinstance(later.targets[0], ast.Name) and later.targets[0].id == name):
                    return []  # the later assignment declares it
                break
        for later in self.following:
            for n in ast.walk(later):
                if (isinstance(n, ast.AugAssign) and isinstance(n.op, ast.Add) and isinstance(n.target, ast.Name)
                        and n.target.id == name and self._list_of(n.value)):
                    t = self._list_of(n.value)
                    self.declared.add(name)
                    self.types[name] = t
                    self.used |= self._type_names(t)
                    return [f"{indent}var {name} = {t}()"]
            for call in ast.walk(later):
                if not isinstance(call, ast.Call) or not isinstance(call.func, ast.Attribute):
                    continue
                t = None
                if ast.unparse(call.func) == f"{name}.append" and len(call.args) == 1:
                    t = self.type_of(call.args[0])
                    t = t and f"List[{t}]"
                for i, a in enumerate(call.args):
                    a = a.value if isinstance(a, ast.Starred) else a  # `*x` passes the list too
                    if isinstance(a, ast.Name) and a.id == name:
                        t = self.api.param(self.type_of(call.func.value), call.func.attr, i, len(call.args), lists=True)
                if t and t.startswith("List["):
                    self.declared.add(name)
                    self.types[name] = t
                    self.used |= self._type_names(t)
                    return [f"{indent}var {name} = {t}()"]
        if self.probing:
            self.declared.add(name)
            return []
        raise Untranslatable(f"the empty list `{name} = []`, whose element type Mojo needs")

    def stmt(self, node, indent):
        method = getattr(self, "s_" + type(node).__name__, None)
        if method is None:
            raise Untranslatable(f"{type(node).__name__} statement `{ast.unparse(node).splitlines()[0]}`")
        return method(node, indent)

    def s_Expr(self, node, indent):
        if isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            return []  # a docstring
        if ast.unparse(node.value) == "gc.collect()":
            return []  # Mojo destroys values deterministically; `del` already ended them
        if isinstance(node.value, ast.Call) and ast.unparse(node.value.func) == "sys.exit" and len(node.value.args) == 1:
            self.used.add("assert_true")
            return [f'{indent}assert_true({self.expr(node.value.args[0])} == 0, "example returned a nonzero exit status")']
        if self.type_of(node.value):
            return [f"{indent}_ = {self.expr(node.value)}"]  # Python discards a result silently
        return [indent + self.expr(node.value)]

    def s_Delete(self, node, indent):
        # `del x` ends a lifetime; in Mojo, moving the value out does.
        if not all(isinstance(t, ast.Name) for t in node.targets):
            raise Untranslatable(f"`{ast.unparse(node)}`")
        return [f"{indent}_ = {t.id}^" for t in node.targets]

    def s_Pass(self, node, indent):
        return [indent + "pass"]

    def _target(self, name, value, indent):
        if name in self.declared:
            self.reassigned.add(self.names.get(name, name))
            return [f"{indent}{self.names.get(name, name)} = {value}"]
        self.declared.add(name)
        return [f"{indent}var {name} = {value}"]

    def s_Assign(self, node, indent):
        if len(node.targets) != 1:
            raise Untranslatable(f"chained assignment `{ast.unparse(node)}`")
        target, value = node.targets[0], self._copied(node.value)
        if isinstance(target, ast.Name):
            if self.is_model_value(node.value):
                self.model_values.add(target.id)
            else:
                self.model_values.discard(target.id)
            t = self.type_of(node.value)
            integer = _integer_constant(node.value)
            if integer is not None and not -(2**63) <= integer < 2**63:
                self.used.add("Integer")
                t, value = "Integer", f"Integer({integer})"
            if target.id in self.declared and t and self.types.get(target.id) not in (None, t):
                # Python rebinds the name to a value of another type; Mojo needs a new variable.
                self.counter += 1
                new = f"{target.id}_{self.counter}"
                self.names[target.id] = new
                self.types[target.id] = t
                return [f"{indent}var {new} = {value}"]
            if t and target.id not in self.declared:
                self.types[target.id] = t
            if (isinstance(node.value, ast.Constant) and node.value.value is None
                    and target.id not in self.declared):
                return self._placeholder(target.id, indent)
            if isinstance(node.value, ast.List) and target.id not in self.declared:
                # A list literal alone is a fixed-size `Array` in Mojo.
                if not node.value.elts:
                    return self._empty_list(target.id, indent)
                self.declared.add(target.id)
                return [f"{indent}var {target.id}: List[type_of({self.expr(node.value.elts[0])})] = {value}"]
            return self._target(target.id, value, indent)
        if isinstance(target, ast.Tuple) and all(isinstance(e, ast.Name) for e in target.elts):
            self.counter += 1
            tmp = f"_values{self.counter}"
            out = [f"{indent}var {tmp} = {value}"]
            for i, e in enumerate(target.elts):
                out += self._target(e.id, f"{tmp}[{i}]", indent)
            return out
        if isinstance(target, (ast.Subscript, ast.Attribute)):
            return [f"{indent}{self.expr(target)} = {value}"]
        raise Untranslatable(f"assignment to `{ast.unparse(target)}`")

    def _list_of(self, node):
        """The list type that `xs += node` makes of an empty `xs`: the type of
        a list, or a list of what iterating `node` gives."""
        t = self.type_of(node)
        if t and t.startswith("List["):
            return t
        found = self.api.results.get((t, "__iter__"), set())
        if len(found) == 1 and next(iter(found)).startswith("OwnedIterator["):
            return f"List[{next(iter(found))[len('OwnedIterator['):-1]}]"
        return None

    def _placeholder(self, name, indent):
        """`x = None` before `x` gets a value: Python's way to declare it. In
        Mojo, `var x: T`, typed by the first later assignment; if Python
        reads `x` first, `var x: Optional[T] = None`, which compares unequal
        to any `T`, as `None` does."""
        for later in self.following:
            for n in ast.walk(later):
                if (isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in n.targets)
                        and self.type_of(n.value)):
                    t = self.type_of(n.value)
                    self.declared.add(name)
                    self.types[name] = t
                    self.used |= self._type_names(t)
                    if _read_first(name, self.following):
                        return [f"{indent}var {name}: Optional[{t}] = None"]
                    return [f"{indent}var {name}: {t}"]
        if self.probing:
            self.declared.add(name)
            return []
        raise Untranslatable(f"`{name} = None`, whose later type is not known")

    def _type_names(self, t):
        """The names in a Mojo type that the module imports."""
        return set(re.findall(r"\w+", t)) & (self.exported | {"Integer", "Rational"})

    def s_AugAssign(self, node, indent):
        op = OPS.get(type(node.op))
        if op is None:
            raise Untranslatable(f"operator in `{ast.unparse(node)}`")
        target, value = self.type_of(node.target) or "", self.type_of(node.value) or ""
        if isinstance(node.op, ast.Add) and target.startswith("List[") and not value.startswith("List["):
            # `xs += t` appends what iterating `t` gives, such as a term's children.
            self.counter += 1
            item = f"_item{self.counter}"
            return [f"{indent}for {item} in {self.expr(node.value)}:",
                    f"{indent}    {self.expr(node.target)}.append({item})"]
        return [f"{indent}{self.expr(node.target)} {op}= {self.expr(node.value)}"]

    def s_Assert(self, node, indent):
        test = node.test
        if (isinstance(test, ast.Compare) and len(test.ops) == 1 and isinstance(test.ops[0], ast.IsNot)
                and isinstance(test.comparators[0], ast.Constant) and test.comparators[0].value is None):
            t = self.type_of(test.left)
            if t and not t.startswith("Optional["):
                return [f"{indent}_ = {self.expr(test.left)}  # a `{t}` is never None"]
        if isinstance(test, ast.UnaryOp) and isinstance(test.op, ast.Not):
            self.used.add("assert_false")
            return [f"{indent}assert_false({self.expr(test.operand)})"]
        self.used.add("assert_true")
        return [f"{indent}assert_true({self.expr(test)})"]

    def condition(self, node):
        """`node` as a condition. A variable holding a cvc5 object whose class
        has neither `__bool__` nor `__len__` is true in Python, whatever its value."""
        if isinstance(node, ast.Name) and self.type_of(node) in self.api.always_true:
            return "True"
        return self.expr(node)

    def _note(self, test):
        """A comment for a condition that `condition` made constant."""
        if isinstance(test, ast.Name) and self.type_of(test) in self.api.always_true:
            return f"  # `{test.id}`, a `{self.type_of(test)}`, is true in Python"
        return ""

    def s_If(self, node, indent):
        out = ([f"{indent}if {self.condition(node.test)}:{self._note(node.test)}"]
               + self.block(node.body, indent + "    "))
        if node.orelse:
            out += [f"{indent}else:"] + self.block(node.orelse, indent + "    ")
        return out

    def s_For(self, node, indent):
        target = node.target
        names = [e.id for e in target.elts if isinstance(e, ast.Name)] if isinstance(target, ast.Tuple) else []
        if node.orelse or not (isinstance(target, ast.Name) or len(names) == len(getattr(target, "elts", ()))):
            raise Untranslatable(f"loop `{ast.unparse(node).splitlines()[0]}`")
        it = node.iter
        if isinstance(target, ast.Name) and self._list_of(it):
            self.types[target.id] = self._list_of(it)[5:-1]
        if (len(names) == 2 and isinstance(it, ast.Call) and isinstance(it.func, ast.Attribute)
                and it.func.attr == "items" and (self.type_of(it.func.value) or "").startswith("Dict[")):
            # A Mojo dict's items are entries with a key and a value.
            self.counter += 1
            entry = f"_entry{self.counter}"
            head = [f"{indent}for {entry} in {self.expr(it)}:"]
            body = []
            for name, field in zip(names, ("key", "value")):
                body += self._target(name, f"{entry}.{field}", indent + "    ")
            return head + body + self.block(node.body, indent + "    ")
        self.declared |= set(names) if names else {target.id}
        return [f"{indent}for {ast.unparse(target)} in {self.expr(it)}:"] + self.block(node.body, indent + "    ")

    def s_While(self, node, indent):
        return ([f"{indent}while {self.condition(node.test)}:{self._note(node.test)}"]
                + self.block(node.body, indent + "    "))

    def s_Return(self, node, indent):
        return [indent + ("return " + self._copied(node.value) if node.value else "return")]

    def s_Break(self, node, indent):
        return [indent + "break"]

    def s_Continue(self, node, indent):
        return [indent + "continue"]

    def s_With(self, node, indent):
        item = node.items[0].context_expr if len(node.items) == 1 else None
        if isinstance(item, ast.Call) and ast.unparse(item.func) in self.null_contexts:
            return self.block(node.body, indent)  # a context manager that does nothing
        if not (isinstance(item, ast.Call) and ast.unparse(item.func) == "pytest.raises"):
            raise Untranslatable(f"`with {ast.unparse(node.items[0])}`")
        error = ast.unparse(item.args[0]) if item.args else "Exception"
        wrong_types = self.argument_rejection(node.body)
        if error in ("TypeError", "ValueError") or wrong_types:
            self.rejections.add(node.lineno)
            if node.lineno == self.compile_failure_line:
                return [indent + "# Expected compile failure starts here"] + self.block(node.body, indent)
            # The Python wrapper checks its arguments at run time; Mojo's types, at compile time.
            out = ([f"{indent}# Python expects {error}; Mojo rejects these arguments at compile time:"]
                   + [f"{indent}#     {line}" for b in node.body for line in ast.unparse(b).splitlines()])
            if wrong_types and len(node.body) == 1 and isinstance(node.body[0], ast.Expr):
                call = node.body[0].value
                if isinstance(call, ast.Call) and len(call.args) == 1 and isinstance(call.args[0], ast.Call):
                    # Python evaluates the inner call first. Keep checking that
                    # runtime rejection as well as the outer static mismatch.
                    inner = ast.With(items=node.items, body=[ast.Expr(value=call.args[0])], lineno=node.lineno)
                    out += self.s_With(inner, indent)
            return out
        self.counter += 1
        self.used.add("assert_true")
        flag = f"_raised{self.counter}"
        return ([f"{indent}var {flag} = False", f"{indent}try:"]
                + self.block(node.body, indent + "    ")
                + [f"{indent}except:", f"{indent}    {flag} = True",
                   f'{indent}assert_true({flag}, "expected an error")'])

    def argument_rejection(self, body):
        """Signature-proven class mismatches or excess positional arguments.

        Numeric conversions and ambiguous overloads keep their normal checks.
        """
        for statement in body:
            for call in ast.walk(statement):
                if not isinstance(call, ast.Call) or not isinstance(call.func, ast.Attribute):
                    continue
                owner = self.type_of(call.func.value)
                overloads = self.api.params.get((owner, call.func.attr), ())
                if (overloads and (owner, call.func.attr) not in self.api.variadics
                        and len(call.args) > max(map(len, overloads))):
                    return True
                for i, value in enumerate(call.args):
                    expected = self.api.param(owner, call.func.attr, i, len(call.args))
                    actual = self.type_of(value)
                    if expected in self.exported and actual in self.exported | {"String", "Int", "Bool", "Float64"} and expected != actual:
                        return True
        return False

    def s_Try(self, node, indent):
        """A bare catch in the legacy exception example; stop at a static rejection.

        Python never reaches later statements after that rejected call. Keep
        its evaluated prefix in an isolated compile-fail fixture, rather than
        translating unreachable legacy names and reporting a spurious error.
        """
        if (node.orelse or node.finalbody or len(node.handlers) != 1
                or node.handlers[0].type is not None or node.handlers[0].name
                or not all(isinstance(s, ast.Pass) for s in node.handlers[0].body)):
            raise Untranslatable("try statement with a nontrivial handler")
        lines = []
        for statement in node.body:
            if self.argument_rejection([statement]):
                self.rejections.add(node.lineno)
                if node.lineno == self.compile_failure_line:
                    return [line[4:] for line in lines] + [indent + "# Expected compile failure starts here"] + self.stmt(statement, indent)
                return [indent + "# Argument rejection checked by a separate compile-fail fixture:",
                        indent + "# " + ast.unparse(statement)]
            lines += self.stmt(statement, indent + "    ")
        return [indent + "try:"] + lines + [indent + "except:", indent + "    pass"]

    # -- functions ---------------------------------------------------------

    def _probe(self, fn, param_types=None):
        """The variables' types, from a first pass, so that a declaration can
        use what later statements tell about a variable."""
        probe = Translator(self.api, self.fixtures, self.null_contexts, self.helpers, self.compile_failure_line, self.model_check)
        probe.probing = True
        try:
            probe.helper(fn, param_types) if param_types is not None else probe.test(fn)
        except Untranslatable:
            pass
        return probe.types

    def helper(self, fn, param_types):
        """A module function the tests call, its parameters typed from the calls."""
        if not self.probing:
            self.types.update(self._probe(fn, param_types))
        for a, t in zip(fn.args.args, param_types):
            self.types[a.arg] = t
            self.declared.add(a.arg)
            self.used |= self._type_names(t)
        body = self.block(fn.body, "    ")
        defaults = [None] * (len(fn.args.args) - len(fn.args.defaults)) + fn.args.defaults
        # Python may rebind a parameter; a Mojo parameter is immutable unless `var`.
        params = [f"{'var ' if a.arg in self.reassigned else ''}{a.arg}: {t}"
                  + (f" = {self.expr(d)}" if d is not None else "")
                  for a, t, d in zip(fn.args.args, param_types, defaults)]
        returns = {self.type_of(r.value) for r in ast.walk(fn) if isinstance(r, ast.Return) and r.value}
        if None in returns or len(returns) > 1:
            raise Untranslatable(f"the return type of `{fn.name}` is not known")
        result = f" -> {returns.pop()}" if returns else ""
        self.used |= self._type_names(result)
        return [f"def {fn.name}({', '.join(params)}) raises{result}:"] + body, (result[4:] or None)

    def test(self, fn):
        # A literal list can be unpacked into fixed arguments only if its sole
        # uses are starred calls. Any other use may change its length.
        stores, loads = {}, {}
        for node in ast.walk(fn):
            if isinstance(node, ast.Name):
                (stores if isinstance(node.ctx, ast.Store) else loads).setdefault(node.id, []).append(node)
        stars = {id(n.value) for n in ast.walk(fn) if isinstance(n, ast.Starred)}
        for node in ast.walk(fn):
            if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name) and isinstance(node.value, ast.List):
                name = node.targets[0].id
                if len(stores[name]) == 1 and all(id(n) in stars for n in loads.get(name, [])):
                    self.literal_lengths[name] = len(node.value.elts)
        if not self.probing:
            self.types.update(self._probe(fn))
        lines = [f"def {fn.name}() raises:"]
        for p in fn.args.args:
            lines += self._fixture(p.arg, "    ")
        body = self.block(fn.body, "    ")
        return lines + body

    def _fixture(self, name, indent):
        if name in self.declared:
            return []
        if name not in self.fixtures:
            raise Untranslatable(f"fixture `{name}`")
        params, value = self.fixtures[name]
        out = []
        for p in params:
            out += self._fixture(p, indent)
        if self.type_of(value):
            self.types[name] = self.type_of(value)
        return out + self._target(name, self.expr(value), indent)


def unmirrored_methods(snap):
    """{Python method name: why it is not mirrored}, for names no mirrored method has."""
    mirrored, out = set(), {}
    for info in snap["python"].values():
        for name, m in info["methods"].items():
            b = m["binding"]
            if b["status"] in gen_api.NOT_MIRRORED:
                out.setdefault(name, b.get("reason", "deprecated in cvc5"))
            else:
                mirrored.add(name)
    return {n: r for n, r in out.items() if n not in mirrored}


def exported_names(snap):
    """The names `cvc5_mojo` exports: classes, enums and public hand-written types."""
    model, _ = gen_api.generated(snap)
    names = set(model.classes) | {i["enum"] for i in snap["c_types"].values() if i["kind"] == "enum"}
    for frag in model.manual.values():
        names |= set(frag["public"])
    return names


def result_types(snap):
    """{(class, method): {Mojo result types of its overloads}}, from the
    generated signatures."""
    model, table = gen_api.generated(snap)
    out = {}
    for cls, methods in table.items():
        for name, (ovs, _) in methods.items():
            if ovs:
                for sig in gen_api.signatures(model, cls, name, ovs):
                    if " -> " in sig:
                        out.setdefault((cls, name), set()).add(sig.rsplit(" -> ", 1)[1])
    return out


def parameter_types(snap, *, variadic=False):
    """{(class, method): [[Mojo parameter types] per overload]}, from the
    generated signatures, or {(class, method): {variadic element types}}.

    Fixed and variadic parameters share the same signature parser.
    """
    model, table = gen_api.generated(snap)
    out = {}
    for cls, methods in table.items():
        for name, (ovs, _) in methods.items():
            for sig in (gen_api.signatures(model, cls, name, ovs) if ovs else []):
                params = reference._split(sig[sig.index("(") + 1 : sig.rindex(")")])
                types = [p.split(":", 1)[1].split("=")[0].strip() for p in params[1:] if ":" in p
                         and p.startswith("*") == variadic]
                if variadic:
                    if types:
                        out.setdefault((cls, name), set()).update(types)
                else:
                    out.setdefault((cls, name), []).append(types)
    return out


def delegated_methods(snap):
    """{class: {deprecated method: (getter class, method)}} for deprecated methods
    that Python implements on another object (`Solver.mkInteger` calls
    `self.tm.mkInteger`); the bindings do not mirror them."""
    owners = {"tm": "TermManager", "solver": "Solver", "sm": "SymbolManager"}
    out = {}
    for cls, info in snap["python"].items():
        for name, m in info["methods"].items():
            if m["binding"]["status"] == "deprecated" and len(m["delegates"]) == 1:
                obj, method = m["delegates"][0].split(".", 1)
                out.setdefault(cls, {})[name] = (owners[obj], method)
    return out


def _plugin_class(node, api):
    """Translate simple Python Plugin subclasses to shared Mojo trait conformers.

    Constructor parameter types come from the extracted base constructor.
    Fields and helper results are inferred by the ordinary expression translator.
    Unsupported inheritance, dynamic names and changed base calls fail closed.
    """
    if [ast.unparse(b) for b in node.bases] != ["Plugin"] or node.decorator_list or node.keywords:
        raise Untranslatable("only undecorated Plugin subclasses are supported")
    methods = {m.name: m for m in node.body if isinstance(m, ast.FunctionDef)}
    if len(methods) != len(node.body) or "__init__" not in methods:
        raise Untranslatable("plugin class requires methods and an explicit constructor")
    ctor = methods["__init__"]
    native_params = reference._split(api.plugin_init)[1:]
    types = [p.replace("not None", "").strip().split()[0] for p in native_params]
    if len(ctor.args.args) != len(types) + 1 or any(t not in api.exported for t in types):
        raise Untranslatable("plugin constructor does not match the typed base constructor")
    fields, bodies, used = {}, [], {"Plugin"} | set(types)
    for name, original in methods.items():
        fn = copy.deepcopy(original)
        if fn.decorator_list or fn.args.defaults or fn.args.vararg or fn.args.kwarg or fn.args.kwonlyargs or fn.args.posonlyargs:
            raise Untranslatable("plugin methods require simple positional parameters")
        body = []
        for statement in fn.body:
            if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Call):
                call = statement.value
                if ast.unparse(call.func).startswith("super()."):
                    if (ast.unparse(call.func) != "super()." + name or name not in ("__init__", "notifySatClause", "notifyTheoryLemma")
                            or [ast.unparse(a) for a in call.args] != [a.arg for a in fn.args.args[1:]] or call.keywords):
                        raise Untranslatable("unsupported plugin base call")
                    continue  # the trait's constructor and notification defaults have no body
            body.append(statement)
        fn.body = body
        t = Translator(api, {})
        args = [a.arg for a in fn.args.args]
        t.types[args[0]] = node.name
        t.declared.add(args[0])
        if name == "__init__":
            params = types
        elif ("Plugin", name) in api.params:
            variants = api.params["Plugin", name]
            if len(variants) != 1:
                raise Untranslatable("ambiguous plugin callback signature")
            params = list(variants[0])
        else:
            params = []
        if name == "getName":
            if len(body) != 1 or not isinstance(body[0], ast.Return) or not isinstance(body[0].value, ast.Constant) or not isinstance(body[0].value.value, str):
                raise Untranslatable("plugin getName must return a constant string")
            lines = ["@staticmethod", "def getName() -> StaticString:", "    return " + _string(body[0].value.value)]
            result = "StaticString"
        else:
            if len(params) != len(args) - 1:
                raise Untranslatable("cannot infer plugin method parameters")
            for arg, kind in zip(args[1:], params):
                t.types[arg] = kind
                t.declared.add(arg)
                t.used |= t._type_names(kind)
            if name == "__init__":
                for statement in body:
                    if not isinstance(statement, ast.Assign) or len(statement.targets) != 1 or not isinstance(statement.targets[0], ast.Attribute) or ast.unparse(statement.targets[0].value) != args[0]:
                        raise Untranslatable("plugin constructor requires direct field assignments")
                    field, kind = statement.targets[0].attr, t.type_of(statement.value)
                    if kind is None:
                        raise Untranslatable("cannot infer plugin field type")
                    fields[field] = kind
                    api.fields[node.name, field] = kind
            lines = t.block(body, "    ")
            result = t.type_of(body[-1].value) if body and isinstance(body[-1], ast.Return) else None
            if name == "check":
                result = "List[Term]"
            convention = "out" if name == "__init__" else "mut"
            signature = f"def {name}({convention} self" + "".join(f", {a}: {ty}" for a, ty in zip(args[1:], params)) + ") raises"
            lines = [signature + (f" -> {result}" if result else "") + ":"] + lines
        bodies += [""] + ["    " + line for line in lines]
        if result:
            t.used |= t._type_names(result)
        used |= t.used
        if result:
            api.results[f"ArcPointer[{node.name}]", name] = {result}
    api.plugins[node.name] = types
    return [f"struct {node.name}(Plugin):"] + [f"    var {n}: {ty}" for n, ty in fields.items()] + bodies, used


def translate_file(path, api, left_out=None, only=None, compile_failure_line=None):
    """Translate one test module. Returns {"text": Mojo source, "run": [the
    tests it runs], "left_out": {test: reason}, "not_translated": {test:
    reason}, "stale": {test: why}}. The tests in `left_out` (overrides.toml)
    are translated but not emitted; an entry for a test that does not exist
    or is not translated anyway is stale. With `only`, the module runs just
    that test, left out or not."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    # Local user classes must not alter the API shared by other test modules.
    api = copy.copy(api)
    api.plugins, api.fields, api.results = {}, dict(api.fields), dict(api.results)
    classes, class_errors = {}, {}
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            try:
                classes[node.name] = (node, *_plugin_class(node, api))
            except Untranslatable as e:
                class_errors[node.name] = str(e)
    fixtures, tests, helpers, null_contexts = {}, [], {}, set()
    is_test = lambda n: n.name.startswith("test")  # pytest's default
    for node in tree.body:
        if not isinstance(node, ast.FunctionDef):
            continue
        decorators = [ast.unparse(d) for d in node.decorator_list]
        if "contextmanager" in decorators and [ast.unparse(b) for b in node.body] == ["yield"]:
            null_contexts.add(node.name)
        elif "pytest.fixture" in decorators:
            ret = node.body[-1]
            if not isinstance(ret, ast.Return) or len(node.body) != 1:
                raise SystemExit(f"{path.name}: fixture `{node.name}` is not a single return")
            fixtures[node.name] = ([a.arg for a in node.args.args], ret.value)
        elif is_test(node):
            tests = [t for t in tests if t.name != node.name] + [node]  # the last definition counts
        else:
            helpers[node.name] = node
    left_out, stale = dict(left_out or {}), {}
    for name in list(left_out):
        if name not in {t.name for t in tests}:
            stale[name] = "no such test"
            del left_out[name]
    if only:
        tests = [t for t in tests if t.name == only]
        left_out = {}
    not_translated = {}
    typed, helper_lines = _helpers(api, helpers, tests, fixtures, null_contexts, not_translated)
    bodies, used, rejections = [], set(), {}
    for fn in tests:
        bad_class = next((n.id for n in ast.walk(fn) if isinstance(n, ast.Name) and n.id in class_errors), None)
        if bad_class:
            not_translated[fn.name] = f"class `{bad_class}`: {class_errors[bad_class]}"
            continue
        missing = [n.id for n in ast.walk(fn) if isinstance(n, ast.Name) and n.id in helpers and n.id not in typed]
        if missing:
            not_translated[fn.name] = f"calls the helper `{missing[0]}`, not translated: {not_translated[missing[0]]}"
            continue
        t = Translator(api, fixtures, null_contexts, typed, compile_failure_line)
        try:
            lines = t.test(fn)
        except Untranslatable as e:
            not_translated[fn.name] = str(e)
            continue
        if fn.name not in left_out:
            bodies.append((fn.name, lines))
            used |= t.used
            rejections[fn.name] = sorted(t.rejections)
    for name in list(left_out):
        if name in not_translated:
            stale[name] = f"not translated anyway: {not_translated[name]}"
            del left_out[name]
    not_translated = {n: r for n, r in not_translated.items() if n in {t.name for t in tests}}
    names = [n for n, _ in bodies]
    not_run = ([f"{n}: left out (bindgen/overrides.toml): {r}" for n, r in left_out.items()]
               + [f"{n}: not translated: {r}" for n, r in not_translated.items()])
    main = ["def main() raises:", "    var failed = 0"]
    for n in names:
        main += ["    try:", f"        {n}()", f'        print("PASS {n}")', "    except e:",
                 f'        print("FAIL {n}:", e)', "        failed += 1"]
    main += ["    if failed:", f'        raise Error(String(failed, " of {len(names)} tests failed"))',
             f'    print("{path.stem}: {len(names)} tests passed")']
    needed = {n.id for fn in tests if fn.name in names for n in ast.walk(fn) if isinstance(n, ast.Name)}
    class_functions = [(node, lines) for name, (node, lines, _) in classes.items() if name in needed]
    for name in needed & classes.keys():
        used |= classes[name][2]
    text = _module(f"{TEST_DIR}/{path.name}", f"Unit tests `{path.name}` of cvc5's Python API, translated to Mojo.",
                   not_run, used, helpers, typed, helper_lines, class_functions +
                   [(fn, lines) for fn in tests for n, lines in bodies if n == fn.name] + [(None, main)])
    return {"text": text, "run": names, "left_out": left_out, "not_translated": not_translated,
            "stale": stale, "rejections": rejections}


