def compile_failures(path, api, tests):
    """Exercise argument-rejection blocks from the runnable upstream tests."""
    out = {}
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for fn in tree.body:
        if not isinstance(fn, ast.FunctionDef) or fn.name not in tests:
            continue
        rejected = translate_file(path, api, only=fn.name)["rejections"][fn.name]
        for node in ast.walk(fn):
            if not isinstance(node, ast.With) or len(node.items) != 1:
                continue
            if node.lineno not in rejected:
                continue
            fixture = translate_file(path, api, only=fn.name, compile_failure_line=node.lineno)
            if fixture["run"] != [fn.name]:
                raise SystemExit(f"cannot translate compile-fail block {path.name}:{node.lineno}: {fixture['not_translated']}")
            lines = fixture["text"].splitlines()
            marker = next(i for i, line in enumerate(lines) if "# Expected compile failure starts here" in line)
            name = f"{path.stem}__{fn.name}__{node.lineno}"
            out[name] = {"text": fixture["text"], "line": marker + 2,
                         "source": f"{path.name}:{node.lineno}", "test": fn.name}
    return out


def _helpers(api, helpers, tests, fixtures, null_contexts, not_translated, compile_failure_line=None):
    """Translate the module functions the tests call, their parameter types
    taken from the calls. Each round translates the tests and the helpers
    typed so far, recording argument types, until no more helpers can be
    typed. Returns ({helper: (parameter types, return type)},
    {helper: (lines, names used, compile-failure source lines)}); a helper that cannot be translated is
    in `not_translated` with the reason."""
    typed, lines = {}, {}
    while True:
        calls = {}
        known = {h: typed.get(h, (None, None)) for h in helpers}
        for fn in tests + [helpers[h] for h in typed]:
            if fn.name in not_translated:
                continue
            t = Translator(api, fixtures, null_contexts, known, compile_failure_line)
            if fn.name in typed:
                for a, ty in zip(fn.args.args, typed[fn.name][0]):
                    t.types[a.arg] = ty
                    t.declared.add(a.arg)
            try:
                t.block(fn.body, "    ") if fn.name in typed else t.test(fn)
            except Untranslatable:
                pass  # reported when the test itself is translated
            for h, arg_lists in t.helper_calls.items():
                calls.setdefault(h, []).extend(arg_lists)
        progress = False
        for name, arg_lists in calls.items():
            if name in typed or name in not_translated:
                continue
            fn = helpers[name]
            a = fn.args
            if (a.vararg or a.kwarg or a.kwonlyargs or a.posonlyargs
                    or not all(isinstance(d, ast.Constant) for d in a.defaults)):
                not_translated[name] = "its parameters are not all positional, with constant defaults"
                continue
            # A call that leaves out a defaulted argument passes the default's type.
            default_types = [Translator(api, {}).type_of(d) for d in a.defaults]
            first_default = len(a.args) - len(a.defaults)
            arg_lists = [args + default_types[len(args) - first_default:] if len(args) >= first_default else args
                         for args in arg_lists]
            kinds = {tuple(args) for args in arg_lists}
            if len(kinds) > 1 or any(len(args) != len(a.args) for args in kinds):
                not_translated[name] = "the calls pass arguments of different types or numbers"
                continue
            types = next(iter(kinds))
            if None in types:
                continue  # perhaps known in a later round
            t = Translator(api, fixtures, null_contexts, known | {name: (list(types), None)}, compile_failure_line)
            try:
                out, result = t.helper(fn, types)
            except Untranslatable as e:
                not_translated[name] = str(e)
                continue
            typed[name] = (list(types), result)
            lines[name] = (out, t.used, t.rejections)
            progress = True
        if not progress:
            for name in helpers:
                if name not in typed and name not in not_translated:
                    not_translated[name] = ("the types of its arguments are not known" if name in calls else
                                     "not a test (pytest runs functions named `test...`), and no test calls it")
            dropped = True
            while dropped:  # a helper calling one that is not translated
                dropped = False
                for name in list(typed):
                    missing = [n.id for n in ast.walk(helpers[name])
                               if isinstance(n, ast.Name) and n.id in helpers and n.id not in typed]
                    if missing:
                        not_translated[name] = f"calls the helper `{missing[0]}`, not translated"
                        del typed[name], lines[name]
                        dropped = True
            return typed, lines


def main(argv=None):
    """Translate every test file and example into tests/cvc5/ and write the
    summary, translation.json; with names as arguments, just those files."""
    argv = sys.argv[1:] if argv is None else argv
    api = Api(json.loads(config.SNAPSHOT_FILE.read_text(encoding="utf-8")))
    sources = sorted((config.SOURCE_DIR / TEST_DIR).glob("test_*.py"))
    examples = example_sources()
    left_out = left_out_tests()
    stale = [f'overrides.toml [tests] "{stem}.{name}" is stale: no test file {stem}.py'
             for stem in sorted(set(left_out) - {p.stem for p in sources}) for name in left_out[stem]]
    left_out_examples = config.overrides().get("examples", {})
    example_checks = config.overrides().get("example_checks", {})
    stale += [f'overrides.toml [examples] "{name}" is stale: no such example'
              for name in sorted(set(left_out_examples) - {example_name(p) for p in examples})]
    stale += [f'overrides.toml [example_checks] "{name}" is stale: no such example'
              for name in sorted(set(example_checks) - {example_name(p) for p in examples})]
    if argv:
        sources = [p for p in sources if p.stem in argv]
        examples = [p for p in examples if example_name(p) in argv]
    config.CVC5_EXAMPLES_DIR.mkdir(parents=True, exist_ok=True)
    files = {}
    compile_fail = {}
    compile_dir = config.CVC5_TESTS_DIR / "compile_fail"
    compile_dir.mkdir(exist_ok=True)
    for path in sources:
        r = translate_file(path, api, left_out.get(path.stem))
        (config.CVC5_TESTS_DIR / f"{path.stem}.mojo").write_text(r["text"], encoding="utf-8")
        files[path.name] = {k: r[k] for k in ("run", "left_out", "not_translated")}
        for name, fixture in compile_failures(path, api, r["run"]).items():
            (compile_dir / f"{name}.mojo").write_text(fixture.pop("text"), encoding="utf-8")
            compile_fail[name] = fixture
        stale += [f'overrides.toml [tests] "{path.stem}.{n}" is stale: {why}' for n, why in r["stale"].items()]
        print(f"{path.name}: {len(r['run'])} run, {len(r['left_out'])} left out, "
              f"{len(r['not_translated'])} not translated")
    translated = {}
    for path in examples:
        name = example_name(path)
        r = translate_example(path, api)
        target = config.CVC5_EXAMPLES_DIR / f"{name}.mojo"
        if example_checks.get(name) == "model" and (not r.get("model_output") or name in left_out_examples):
            stale.append(f'overrides.toml [example_checks] "{name}" is stale: no runnable model output')
        if r["text"] is None:
            translated[path.name] = {"not_translated": r["not_translated"]}
            if name in left_out_examples:
                stale.append(f'overrides.toml [examples] "{name}" is stale: not translated anyway: '
                             f'{r["not_translated"]}')
            if target.exists():
                target.unlink()  # a translation from before, now gone
        else:
            target.write_text(r["text"], encoding="utf-8")
            translated[path.name] = ({"left_out": left_out_examples[name]} if name in left_out_examples
                                     else {"run": name})
            if r.get("model_output"):
                translated[path.name]["model_output"] = r["model_output"]
            for line in r.get("rejections", []):
                fixture = translate_example(path, api, compile_failure_line=line)
                if fixture["text"] is None:
                    raise SystemExit(f"cannot translate example compile-fail block {path.name}:{line}")
                marker = next(i for i, text in enumerate(fixture["text"].splitlines()) if "# Expected compile failure starts here" in text)
                key = f"example_{name}__{line}"
                (compile_dir / f"{key}.mojo").write_text(fixture["text"], encoding="utf-8")
                compile_fail[key] = dict(line=marker + 2, source=f"{EXAMPLE_DIR}/{path.name}:{line}", example=name)
        print(f"{path.name}: " + ("translated" if r["text"] else f"not translated: {r['not_translated']}"))
    for problem in stale:
        print(f"problem: {problem}")
    if argv:
        return
    for path in compile_dir.glob("*.mojo"):
        if path.stem not in compile_fail and path.read_text().startswith(MARKER):
            path.unlink()
    # `pixi run --locked cvc5-tests` fails while `stale` is not empty.
    summary = {"cvc5": config.pinned()["version"], "source": TEST_DIR, "stale": stale, "files": files,
               "example_source": EXAMPLE_DIR, "examples": translated, "compile_fail": compile_fail}
    config.TRANSLATION_FILE.write_text(json.dumps(summary, indent=1) + "\n", encoding="utf-8")
    count = lambda key: sum(len(f[key]) for f in files.values())
    print(f"wrote {config.CVC5_TESTS_DIR.relative_to(config.ROOT)}: {count('run')} tests run, "
          f"{count('left_out')} left out, {count('not_translated')} not translated; "
          f"{sum('run' in e for e in translated.values())} of {len(translated)} examples run")


if __name__ == "__main__":
    main()
