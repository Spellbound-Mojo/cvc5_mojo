"""Translate cvc5's Python unit tests and examples to Mojo (milestone C2).

Reads test/unit/api/python/test_*.py and the examples of examples/api/python
from the pinned source archive with Python's `ast` module and writes
tests/cvc5/test_*.mojo, tests/cvc5/examples/<name>.mojo, and a summary of
which tests and examples run and why the others do not,
tests/cvc5/translation.json. An example's main block becomes Mojo's `main`;
bindgen.oracle records what the Python example prints, for comparison. Mojo's syntax is
close to Python's, so most of a test carries over as written; the
translation handles what differs:

* pytest fixtures (`tm`, `solver`) become locals at the top of each test;
* the other module functions the tests call become Mojo functions, their
  parameters typed by the arguments at the calls;
* `with pytest.raises(...)` becomes a `try`/`except` that requires an error.
  `TypeError`/`ValueError` blocks and signature-proven type/arity mismatches
  get compile-fail fixtures; nested calls retain their runtime error checks;
* `del x` becomes `_ = x^`, which ends the value's lifetime, and
  `gc.collect()` becomes nothing;
* `assert x` becomes `assert_true(x)`, `assert not x` `assert_false(x)`, and
  `assert x is not None`, for a value of a type that has no `None`, `_ = x`;
* the first assignment to a name declares it with `var`. Mojo needs a type
  where Python's value does not tell it: a list literal alone is a
  fixed-size `Array`, so a list is typed by its first element; an empty list
  by a later use (`x.append(e)`, or a method taking `x`); and `x = None` by
  a later assignment;
* types come from literals, constructors, the generated signatures and the
  helpers' results; a first pass over a function collects them;
* `5 == x` and `[a] == x` become `x == 5` and `x == [a]`: a literal has no
  comparison with the library's types, and a list literal alone is an `Array`;
* `f(*xs)` passes the list `xs` where Python's method takes `*args`, and a
  set or `{}` with at most one element passed to a method becomes a list;
* `for k, v in d.items()` reads a Mojo dict's entries; `len(s)` of a string
  counts code points, as Python's does;
* a deprecated method that Python implements on the term manager
  (`solver.mkInteger(1)`) calls it there (`solver.getTermManager().mkInteger(1)`);
* `str`, `int` and `Fraction` become `String`, `Int` and apn_mojo's `Rational`;
  `math` functions, std.math's;
* an f-string or `"{}".format(x)` becomes `String(...)`, which writes each
  value as Python's `str` does;
* `if x:` on a cvc5 object whose class has neither `__bool__` nor `__len__`
  is `if True:`, as in Python; `xs += t` appends what iterating `t` gives;
* identity comprehensions and required iterable arguments become lists;
  fixed record-field lists can be unpacked only if nothing can mutate them;
* metadata dict access uses the canonical binding struct's typed fields;
  comparisons guard optional/variant values before reading them;
* literal `Fraction(float)` and `Fraction(str)` preserve their distinct exact
  ratios, and wide integer constant locals become `Integer`;
* an example's own `main` becomes a helper whose exit status is checked;
  unreachable statements after a statically rejected call are not emitted;
* examples with a `model` comparison policy evaluate their assertions and
  check printed model values before allowing those output fields to differ.

A test that uses anything else is not translated, with the reason. A test
that translates but cannot pass in Mojo is left out by an entry in the
[tests] table of bindgen/overrides.toml, with the reason; an example whose
output cannot match Python's, by an entry in [examples]. The coverage
report lists both (bindgen.report). Each generated file runs its tests one
by one, prints a line per test, and fails if any test fails;
scripts/run_cvc5_tests.py builds and runs them (`pixi run --locked cvc5-tests`).

Usage: python -m bindgen.translate [test_result ...]   (default: every file
and translation.json)
"""

