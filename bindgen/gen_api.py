"""Generate the base API: Mojo structs and a callback trait for Python classes.

Reads api/cvc5-api.json and writes src/cvc5_mojo/<class>.mojo and the
package's __init__.mojo. Classes, methods and parameters have cvc5's Python names. A
method is one Mojo overload per C function its binding names (see
docs/content/architecture/join.md), built from the C signature:

* the first C parameter is the receiver;
* a `size_t` followed by const arrays is one `List` per array, whose lengths
  must agree; a Python `*args` mapped to the last of them also gets a
  variadic overload; `size_t sizes[]` and `const T* arrays[]` among them are
  one `List[List[...]]`;
* `const char*` is a `String`; it is `Optional[String] = None` where
  Python's default is `None` and cvc5 documents the parameter as "may be
  NULL" (likewise for pointer-owned classes);
* integers are `Int`, range-checked into the C type, except `uint64_t`
  (`UInt64`); `double` is `Float64`;
* handles are the generated classes, and a returned handle is received by
  its type's ownership mode (`own`: wrapped; `anchor`: adopted while retaining its solver), also in
  arrays; a returned pointer-owned object is borrowed and keeps the object
  that returned it alive;
* a returned array with its `size_t*` count is a `List`; other
  out-parameters are returned with the result in a `Tuple`, in C order with
  the C result last; a `const char** error_msg` out-parameter raises when
  cvc5 sets it;
* where the C++ method a C function calls returns or takes a `map[K, V]`
  (`cpp_maps` in the snapshot, from cvc5.pxd), Python uses a dict, and the
  C function's two parallel arrays are one `Dict[K, V]`, returned or taken;
* `__iter__` reads every element with a count function and a get-by-index
  function, and returns an `OwnedIterator` over them.

A method whose binding is `manual` is hand-written in
bindgen/manual/<Class>.mojo: the methods of its `struct <Class>:` are
spliced into the generated class with cvc5's docstrings, and the
definitions after it are appended to the module (see `fragment()`). A
fragment may also add overloads to a generated method.

Python dunders become Mojo traits: `__eq__`/`__ne__` (Equatable), `__lt__`
and the other comparisons (Comparable), `__hash__` (Hashable), and
`__str__`/`__repr__` (Writable, plus a single-pass `toString()`). Mojo requires these to be non-raising, as
destructors and copy constructors are; they abort if cvc5 reports an error,
which it does not for valid handles. Handles may be NULL (a parser returns a
null command at the end of its input), so copying and releasing skip NULL.

`classify()` lists every method that is not generated, with the reason; the
coverage report renders it.

Usage: python -m bindgen.gen_api   (reads api/cvc5-api.json)
"""

