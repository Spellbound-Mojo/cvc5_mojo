# Python dunders that Mojo requires to be non-raising.
COMPARISONS = {"__lt__": "<", "__gt__": ">", "__le__": "<=", "__ge__": ">="}


class Unsupported(Exception):
    """A method or overload the generator cannot produce."""


def snake(name):
    """`TermManager` -> `term_manager`."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def python_params(params):
    """[(name, default or None, star)] from a Cython parameter list, without self."""
    out = []
    for p in reference._split(params):
        p = p.replace("not None", "").strip()
        default = None
        if "=" in p:
            p, default = (x.strip() for x in p.split("=", 1))
        if not p or p == "self":
            continue
        name = p.split()[-1]
        out.append((name.lstrip("*"), default, name.startswith("*")))
    return out


def nullable(f, pname):
    """Whether parameter `pname` of `f` accepts NULL: cvc5 documents it as
    "may be NULL", or the implementation tests it (`null_tested`)."""
    if pname in f.get("null_tested", []):
        return True
    m = re.search(rf"@param\s+{re.escape(pname)}\b(.*?)(?=@\w|\Z)", f["doc"], re.S)
    return bool(m) and "NULL" in m.group(1)


def _escape(text):
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def _sentence(text):
    """A docstring summary as Mojo requires it: capitalized, ending in punctuation."""
    text = " ".join(text.split())
    if text[:1].islower():
        text = text[0].upper() + text[1:]
    if text and text[-1] not in ".!?`":
        text += "."
    return text


def result_name(f):
    """A local name for the C result that no C parameter of `f` uses."""
    name = "result"
    while name in {p["name"] for p in f["params"]}:
        name += "_"
    return name


def _list_result(element, count, expression):
    """Build a counted owned snapshot, adopting each converted element once."""
    return [f"var items = List[{element}](capacity={count})",
            f"for i in range({count}):", f"    items.append({expression})"]


class Param:
    """One Mojo parameter of an overload, and how its argument reaches C."""

    def __init__(self, name, mojo, c_args, prep=(), keep=(), default=None, variadic=False, c_index=()):
        self.name, self.mojo, self.c_args = name, mojo, list(c_args)
        self.prep, self.keep = list(prep), list(keep)
        self.default, self.variadic, self.c_index = default, variadic, list(c_index)
        self.nullable = (False, None)
        self.renames = []

    def rename(self, new):
        """Rename the parameter, and the helper variables derived from its name
        (`{name}_c`, `{name}_keys_c`, ...)."""
        old, self.name = self.name, new
        self.renames.append((old, new))
        sub = lambda s: re.sub(rf"\b{re.escape(old)}(?=\b|_)", new, s)
        self.c_args = [sub(a) for a in self.c_args]
        self.prep = [sub(a) for a in self.prep]
        self.keep = [sub(a) for a in self.keep]
        if self.nullable[1]:
            self.nullable = (self.nullable[0], sub(self.nullable[1]))

    def decl(self):
        if self.variadic:
            return f"*{self.name}: {self.mojo}"
        return f"{self.name}: {self.mojo}" + (f" = {self.default}" if self.default is not None else "")


STRUCT_RE = re.compile(r"^struct (\w+)\b")
METHOD_RE = re.compile(r"^    def (\w+)\s*[\[(]")
PUBLIC_RE = re.compile(r"^(?:struct|trait|comptime|def) ([A-Za-z]\w*)")


def _is_private(name):
    return name.startswith("_") and not (name.startswith("__") and name.endswith("__"))


def fragment(path, classes):
    """Parse a hand-written fragment, bindgen/manual/<Class>.mojo.

    It holds imports, then `struct <Class>:` with methods, then other
    definitions. The methods are spliced into the generated class, the
    definitions appended to its module. Returns (class, {"imports",
    "methods": [(name, lines)], "extra", "public"}).
    """
    rel = path.relative_to(config.ROOT)
    lines = path.read_text(encoding="utf-8").splitlines()
    heads = [i for i, line in enumerate(lines) if (m := STRUCT_RE.match(line)) and m.group(1) in classes]
    if len(heads) != 1:
        raise SystemExit(f"{rel}: expected one `struct <Class>:` naming a generated class")
    start = heads[0]
    cls = STRUCT_RE.match(lines[start]).group(1)
    if lines[start].rstrip() != f"struct {cls}:":
        raise SystemExit(f"{rel}: write `struct {cls}:`; the generator chooses the traits")
    head, in_doc = [], False
    for line in lines[:start]:
        if line.startswith('"""') or in_doc:
            in_doc = (line.count('"""') % 2 == 1) != in_doc
            continue
        if line.strip() and not line.startswith(("from ", "import ", "#")):
            raise SystemExit(f"{rel}: only imports may precede `struct {cls}:`, not `{line.strip()}`")
        head.append(line)
    end = start + 1
    while end < len(lines) and (not lines[end].strip() or lines[end][0].isspace()):
        end += 1
    methods, decorators = [], []
    for line in lines[start + 1 : end]:
        m = METHOD_RE.match(line)
        if m:
            methods.append((m.group(1), decorators + [line]))
            decorators = []
        elif line.startswith("    @"):
            decorators.append(line)
        elif methods:
            methods[-1][1].append(line)
        elif line.strip():
            raise SystemExit(f"{rel}: only methods belong in `struct {cls}:`, not `{line.strip()}`")
    for _, body in methods:
        while body and not body[-1].strip():
            body.pop()
    extra = lines[end:]
    while extra and not extra[0].strip():
        extra.pop(0)
    public = [m.group(1) for line in extra if (m := PUBLIC_RE.match(line))]
    imports = [line for line in head if line.startswith(("from ", "import "))]
    return cls, {"path": rel, "imports": imports, "methods": methods, "extra": extra, "public": public}


def _signature_end(body):
    """The index of the line that ends a method's `def` (after decorators)."""
    depth = 0
    for k, line in enumerate(body):
        if line.strip().startswith("@"):
            continue
        depth += line.count("(") + line.count("[") - line.count(")") - line.count("]")
        if depth == 0 and line.rstrip().endswith(":"):
            return k
    raise SystemExit(f"unterminated signature: {body[0].strip()}")


def _signature_params(sig):
    """The parameter names of a Mojo `def`, without `self`."""
    inner = sig[sig.index("(") + 1 : sig.rindex(")")]
    names = []
    for p in reference._split(inner):
        name = p.split(":")[0].split("=")[0].split()[-1] if p.strip() else ""
        if name and name not in ("self", "*") and not name.startswith("*"):
            names.append(name)
    return names


class Model:
    """The classes to generate, and the rules that build their methods."""

    def __init__(self, snap):
        self.snap = snap
        self.cf = snap["c_functions"]
        self.ct = snap["c_types"]
        self.raw_bound, self.raw_excluded = gen_raw.classify(snap)
        self.classes = {}
        for cls, info in snap["python"].items():
            if all(m["binding"]["status"] in NOT_MIRRORED for m in info["methods"].values()):
                continue
            ctype = info["section"]
            self.classes[cls] = {
                "ctype": ctype,
                "owner": self.ct[ctype]["kind"] == "opaque",
                "callback": info.get("callback", False),
                "prefix": info["prefix"],
                "module": snake(cls),
                "info": info,
            }
        self.by_ctype = {c["ctype"]: cls for cls, c in self.classes.items()}
        self.owners = sorted(cls for cls, c in self.classes.items() if c["owner"])
        self.anchors = {}
        for cls, c in self.classes.items():
            if c["owner"] or c["callback"]:
                continue
            receipt = snap["handles"][c["ctype"]]
            if receipt["receive"] not in ("own", "anchor"):
                raise SystemExit(f"{cls}: unsupported handle receipt mode {receipt['receive']!r}")
            if receipt["receive"] == "anchor":
                owner = self.by_ctype.get(receipt["exporter"])
                if owner not in self.owners:
                    raise SystemExit(f"{cls}: anchor exporter must be a generated pointer owner")
                self.anchors[cls] = owner
        # Every wrapper remembers its term manager, as Python's do; its C type
        # is the one that exports terms.
        self.term_ctype = self.classes["Term"]["ctype"]
        self.tm_ctype = snap["handles"][self.term_ctype]["exporter"]
        self.keepers = self._keepers()
        self.callback_owners = {"Solver", *self.keepers["Solver"]} if "Plugin" in self.classes else set()
        # A native exported handle may retain a callback host after its Mojo
        # owner disappears (notably a command retaining its input parser).
        # Reuse the existing anchor path to retain the Mojo callback storage too.
        for cls, c in self.classes.items():
            if c["owner"] or c["callback"]:
                continue
            exporter = self.by_ctype.get(snap["handles"][c["ctype"]]["exporter"])
            if exporter in self.callback_owners:
                self.anchors[cls] = exporter
        self.manual = self._fragments()
        for cls, c in self.classes.items():
            methods = c["info"]["methods"]
            occupied = set(methods) | {name for name, _ in self.manual.get(cls, {}).get("methods", [])}
            for method, info in methods.items():
                binding = info["binding"]
                for native, name in binding.get("private", {}).items():
                    if (native not in binding.get("c", []) or binding["status"] == "manual"
                            or not re.fullmatch(r"_native_[A-Za-z]\w*", name) or name in occupied):
                        raise SystemExit(f"{cls}.{method}: invalid or colliding private overload {native}: {name}")
                    occupied.add(name)

    def _fragments(self):
        """{class: fragment} for bindgen/manual/*.mojo, checked against the snapshot.

        A public method is a mirrored Python method: all of it when its
        binding is `manual`, else overloads added to the generated ones. The
        fragment may call only C functions of those methods' bindings, and
        must call every one a `manual` binding lists.
        """
        out = {}
        for path in sorted(config.MANUAL_DIR.glob("*.mojo")):
            cls, frag = fragment(path, self.classes)
            rel = frag["path"]
            if path.stem != cls:
                raise SystemExit(f"{rel}: the fragment of {cls} is named {cls}.mojo")
            methods = self.classes[cls]["info"]["methods"] | self.snap.get("extensions", {}).get(cls, {})
            for name, _ in frag["methods"]:
                if name in methods and methods[name]["binding"]["status"] in NOT_MIRRORED:
                    raise SystemExit(f"{rel}: {cls}.{name} is not mirrored")
                if name not in methods and not _is_private(name):
                    raise SystemExit(f"{rel}: {name} is neither a Python method, declared C extension of {cls}, nor private")
            # The bindings name the C functions the hand-written code uses.
            text = "\n".join([line for _, body in frag["methods"] for line in body] + frag["extra"])
            called = set(re.findall(r"\b(cvc5_\w+)\(", text))
            defined = {name for name, _ in frag["methods"] if name in methods}
            allowed = {c for name in defined for c in methods[name]["binding"].get("c", [])}
            listed = {c for name in defined if methods[name]["binding"]["status"] == "manual"
                      for c in methods[name]["binding"]["c"]}
            if not listed <= called <= allowed:
                raise SystemExit(f"{rel}: the fragment calls {sorted(called - allowed)} that the bindings of its "
                                 f"methods do not name, and does not call {sorted(listed - called)} that "
                                 f"overrides.toml lists for its manual methods")
            out[cls] = frag
        return out

    def _keepers(self):
        """{owner class: [owner classes whose C functions return it, borrowed]}.

        A borrowed object's state keeps the state of the object that returned
        it alive, so these relations must not form a cycle.
        """
        out = {cls: [] for cls in self.owners}
        for name, f in self.cf.items():
            base, depth, _ = gen_raw._split(f["returns"])
            if depth != 1 or base not in self.by_ctype or not self.classes[self.by_ctype[base]]["owner"]:
                continue
            first = f["params"][0]["type"] if f["params"] else ""
            src = self.by_ctype.get(gen_raw._split(first)[0]) if first.endswith("*") else None
            if src and self.classes[src]["owner"] and not name.endswith("_new"):
                out[self.by_ctype[base]].append(src)
        def reaches(a, b, seen=()):
            return any(k == b or (k not in seen and reaches(k, b, seen + (k,))) for k in out[a])
        for cls in out:
            if reaches(cls, cls):
                raise SystemExit(f"borrowed pointer-owned objects form a cycle through {cls}")
        return {cls: sorted(set(v)) for cls, v in out.items()}

    # -- lifecycle -------------------------------------------------------

    def lifecycle(self, cls):
        """(copy, release) for a handle class; (new, delete) for an owner."""
        c = self.classes[cls]
        if not c["owner"]:
            names = (c["prefix"] + "copy", c["prefix"] + "release")
        else:
            names = c_headers.owner_lifecycle(self.cf, c["ctype"])
        for n in names:
            if n not in self.raw_bound:
                raise SystemExit(f"{cls}: lifecycle function {n} is not in the raw layer")
        return names

    # -- types -----------------------------------------------------------

    def _class_of(self, ctype, what):
        if ctype not in self.by_ctype:
            raise Unsupported(f"{what} `{ctype}` has no generated class")
        return self.by_ctype[ctype]

    def _input_array(self, p):
        base, depth, _ = gen_raw._split(p["type"])
        return p["type"].startswith("const ") and (depth >= 2 if base == "char" else depth >= 1)

    def shape(self, cname, receiver=True):
        """Split a C signature into input groups, out-parameters and an array count."""
        offset = 1 if receiver else 0
        params = [dict(p, _index=k + offset) for k, p in enumerate(self.cf[cname]["params"][offset:])]
        groups, outs, count, i = [], [], None, 0
        while i < len(params):
            p = params[i]
            base, depth, const = gen_raw._split(p["type"])
            if base == "size_t" and depth == 0:
                j = i + 1
                while j < len(params):
                    if self._nested(params, j):
                        j += 2
                    elif self._input_array(params[j]):
                        j += 1
                    else:
                        break
                if j > i + 1:
                    groups.append(("lists", params[i + 1 : j], p))
                    i = j
                    continue
            if base == "size_t" and depth == 1 and not const:
                count = p
            elif depth >= 1 and not const and base != "void" and not (
                self.ct.get(base, {}).get("kind") == "opaque" and depth == 1
            ):
                outs.append(p)
            else:
                groups.append(("one", p))
            i += 1
        return groups, outs, count

    def _nested(self, params, j):
        """Whether `params[j]` and `params[j + 1]` are `size_t sizes[]` and
        `const T* arrays[]`: C's form of a list of lists of handles."""
        if j + 1 >= len(params) or params[j]["type"] != "size_t*":
            return False
        base, depth, _ = gen_raw._split(params[j + 1]["type"])
        return (params[j + 1]["type"].startswith("const ") and depth == 2
                and self.ct.get(base, {}).get("kind") == "handle")

    def _nested_input(self, n, p):
        """Convert a `List[List[...]]` into C's inner arrays `{n}_inner`, their
        lengths `{n}_sizes` and their pointers `{n}_c` for C array `p`:
        (Mojo element type, prep lines, buffers to keep alive)."""
        base, _, _ = gen_raw._split(p["type"])
        cls = self._class_of(base, "array element")
        # Removing one pointer level gives the same flat array shape as any
        # other handle input; keep its conversion policy in _array_input.
        _, inner, _ = self._array_input("inner", "xs", dict(p, type=p["type"][:-1]))
        prep = [f"var {n}_inner = List[List[{base}]](capacity=len({n}))",
                f"var {n}_sizes = List[UInt](capacity=len({n}))",
                f"for xs in {n}:"]
        prep += ["    " + line for line in inner]
        prep += [f"    {n}_sizes.append(UInt(len(inner_c)))",
                f"    {n}_inner.append(inner_c^)",
                f"var {n}_c = List[Pointer[{base}, MutUntrackedOrigin]](capacity=len({n}_inner))",
                f"for i in range(len({n}_inner)):",
                f"    {n}_c.append({n}_inner[i].unsafe_ptr().unsafe_origin_cast[MutUntrackedOrigin]())"]
        return f"List[{cls}]", prep, [f"{n}_inner"]

    def _element(self, p):
        """Mojo element type of input array `p`, its raw type, and a template that
        converts element `{x}`."""
        base, depth, _ = gen_raw._split(p["type"])
        info = self.ct.get(base, {})
        if info.get("kind") == "handle" and depth == 1:
            cls = self._class_of(base, "array element")
            return cls, base, "{x}._h"
        if base == "char" and depth == 2:
            return "String", None, None
        if base in INT_IN and depth == 1:
            return "Int", gen_raw.SCALARS[base][0], INT_IN[base].format("{x}")
        if base in OTHER_SCALARS and depth == 1:
            return OTHER_SCALARS[base], OTHER_SCALARS[base], "{x}"
        raise Unsupported(f"array parameter `{p['name']}` of type `{p['type']}`")

    def _array_input(self, var, iterable, p, count=None):
        """Convert the Mojo values of `iterable` into the raw array `{var}_c` for C
        array parameter `p`: (Mojo element type, prep lines, buffers to keep alive).

        Every caller knows the input size. Dict views use their owner's length;
        lists and variadic packs expose their own. Reserve once without changing
        initialized length, conversion order, or the lifetime of backing buffers.
        """
        elem, raw_elem, conv = self._element(p)
        count = count if count is not None else f"len({iterable})"
        if elem == "String":
            prep = [f"var {var}_bytes = List[List[Int8]](capacity={count})",
                    f"var {var}_c = List[CChars](capacity={count})",
                    f"for s in {iterable}:",
                    f"    {var}_bytes.append(c_bytes(s))",
                    f"for i in range(len({var}_bytes)):",
                    f"    {var}_c.append({var}_bytes[i].unsafe_ptr().unsafe_origin_cast[MutUntrackedOrigin]())"]
            return elem, prep, [f"{var}_bytes"]
        prep = [f"var {var}_c = List[{raw_elem}](capacity={count})", f"for x in {iterable}:",
                f"    {var}_c.append({conv.format(x='x')})"]
        return elem, prep, []

    def maps(self, cname):
        """The C++ map declarations (`cpp_maps`) of the C++ methods `cname` calls."""
        maps = self.snap.get("cpp_maps", {})
        return [maps[c] for c in self.cf[cname]["cpp_calls"] if c in maps]

    def _check_map(self, cpp, mojo, what):
        """Check that C++ `map[K, V]` and the Mojo element types of its C arrays agree."""
        expected = [{"string": "String", "uint64_t": "UInt64"}.get(t, t) for t in cpp]
        if expected != list(mojo):
            raise Unsupported(f"{what}: C++ `map[{', '.join(cpp)}]` does not match the C arrays "
                              f"of `{mojo[0]}` and `{mojo[1]}`")

    def _dict_param(self, cname, arrays, size):
        """One `Dict` parameter for a size and two C arrays that are a C++ map."""
        n = gen_raw._identifier(arrays[0]["name"], 0)
        key, key_prep, key_keep = self._array_input(f"{n}_keys", f"{n}.keys()", arrays[0], f"len({n})")
        value, value_prep, value_keep = self._array_input(f"{n}_values", f"{n}.values()", arrays[1], f"len({n})")
        maps = [p for m in self.maps(cname) for p in m["params"].values()]
        self._check_map(maps[0], (key, value), f"`{cname}`")
        return Param(n, f"Dict[{key}, {value}]",
                     [f"UInt(len({n}_keys_c))", f"{n}_keys_c.unsafe_ptr()", f"{n}_values_c.unsafe_ptr()"],
                     key_prep + value_prep, key_keep + value_keep,
                     c_index=[size["_index"], arrays[0]["_index"], arrays[1]["_index"]])

    def input_params(self, cname, receiver=True):
        """The Mojo parameters for the inputs of `cname`, in C order (names are C names)."""
        f = self.cf[cname]
        groups, _, _ = self.shape(cname, receiver)
        # A C++ map parameter is a size and two arrays in C, and a dict in Python.
        map_params = [p for m in self.maps(cname) for p in m["params"].values()]
        pairs = [g for g in groups if g[0] == "lists" and len(g[1]) == 2]
        if map_params and (len(map_params) != 1 or len(pairs) != 1):
            raise Unsupported(f"{len(map_params)} C++ map parameters for {len(pairs)} pairs of C arrays")
        out = []
        for kind, *rest in groups:
            if kind == "lists" and map_params and len(rest[0]) == 2:
                out.append(self._dict_param(cname, *rest))
                continue
            if kind == "lists":
                arrays, size = rest
                first = None
                k = 0
                while k < len(arrays):
                    p = arrays[k]
                    n = gen_raw._identifier(p["name"], 0)
                    if self._nested(arrays, k):
                        # A list of lists: C takes the inner lengths and the inner arrays.
                        p = arrays[k + 1]
                        n = gen_raw._identifier(p["name"], 0)
                        elem, prep, keep = self._nested_input(n, p)
                        ptr_args = [f"{n}_sizes.unsafe_ptr()", f"{n}_c.unsafe_ptr()"]
                        ptr_index = [arrays[k]["_index"], p["_index"]]
                        k += 2
                    else:
                        elem, prep, keep = self._array_input(n, n, p)
                        ptr_args, ptr_index = [f"{n}_c.unsafe_ptr()"], [p["_index"]]
                        k += 1
                    if first is None:
                        first = n
                        c_args = [f"UInt(len({n}_c))"] + ptr_args
                        c_index = [size["_index"]] + ptr_index
                    else:
                        prep = [f"if len({n}) != len({first}):",
                                f'    raise Error("cvc5_mojo: `{n}` and `{first}` must have the same length")'] + prep
                        c_args, c_index = ptr_args, ptr_index
                    out.append(Param(n, f"List[{elem}]", c_args, prep, keep, c_index=c_index))
                continue
            p = rest[0]
            n = gen_raw._identifier(p["name"], 0)
            base, depth, _ = gen_raw._split(p["type"])
            info = self.ct.get(base, {})
            null_ok = nullable(f, p["name"])
            if info.get("kind") == "handle" and depth == 0:
                out.append(Param(n, self._class_of(base, "parameter"), [f"{n}._h"], c_index=[p["_index"]]))
            elif info.get("kind") == "opaque" and depth == 1:
                cls = self._class_of(base, "parameter")
                param = Param(n, cls, [f"{n}._handle()"], c_index=[p["_index"]])
                param.nullable = (null_ok, f"{n}.value()._handle() if {n} else {base}(null[NoneType]())")
                out.append(param)
            elif info.get("kind") == "enum" and depth == 0:
                out.append(Param(n, info["enum"], [n], c_index=[p["_index"]]))
            elif base == "bool" and depth == 0:
                out.append(Param(n, "Bool", [n], c_index=[p["_index"]]))
            elif base in INT_IN and depth == 0:
                out.append(Param(n, "Int", [INT_IN[base].format(n)], c_index=[p["_index"]]))
            elif base in OTHER_SCALARS and depth == 0:
                out.append(Param(n, OTHER_SCALARS[base], [n], c_index=[p["_index"]]))
            elif base == "char" and depth == 1:
                param = Param(n, "String", [f"{n}_c.unsafe_ptr()"], [f"var {n}_c = c_bytes({n})"], c_index=[p["_index"]])
                param.nullable = (null_ok, None)
                out.append(param)
            else:
                raise Unsupported(f"parameter `{p['name']}` of type `{p['type']}`")
        return out

    def _make_optional(self, param):
        """Turn a nullable parameter into `Optional[...] = None`."""
        if param.mojo == "String":
            n = param.name
            param.prep = [f"var {n}_c = c_bytes({n}.value()) if {n} else List[Int8]()",
                          f"var {n}_p = {n}_c.unsafe_ptr().unsafe_origin_cast[MutUntrackedOrigin]() if {n} else null[Int8]()"]
            param.keep = [f"{n}_c"]
            param.c_args = [f"{n}_p"]
        else:
            param.c_args = [param.nullable[1]]
        param.mojo = f"Optional[{param.mojo}]"
        param.default = "None"

    # -- results ---------------------------------------------------------

    def receiver_context(self, cls):
        """API, term-manager and native-handle expressions for a method receiver."""
        if self.classes[cls]["owner"]:
            return "self._o[].api", "self._o[].tm", "self._handle()"
        return "self._api", "self._tm", "self._h"

    def bind_receiver(self, lines, cls):
        """Resolve receipt templates against the actual receiver, including aliases.

        An anchored result needs the exporter's state, either directly from
        that owner or inherited from a handle with the same anchor category.
        Reject missing or mismatched anchors before emitting invalid Mojo.
        """
        _, tm, _ = self.receiver_context(cls)
        owner = cls if self.classes[cls]["owner"] else self.anchors.get(cls)
        anchor = "self._o" if self.classes[cls]["owner"] else "self._anchor.value()"

        def substitute(match):
            required = match[1]
            if owner != required:
                raise Unsupported(f"{cls}: cannot supply {required} anchor for returned handle")
            return anchor

        return [re.sub(r"__ANCHOR_(\w+)__", substitute, line.replace("__TM__", tm)) for line in lines]

    def received(self, ctype, expr, api):
        """A handle `expr` of C type `ctype`, received into its class."""
        cls = self._class_of(ctype, 'result')
        anchor = f", __ANCHOR_{self.anchors[cls]}__" if cls in self.anchors else ""
        return f"{cls}._received({api}, __TM__, {expr}{anchor})"

    def borrowed(self, ctype, expr, receiver):
        """Wrap a pointer-owned return only through an established keeper edge."""
        cls = self._class_of(ctype, 'result')
        if cls not in self.keepers or receiver not in self.keepers[cls]:
            raise Unsupported(f"{receiver}: no borrowed-owner keeper relationship for {cls}")
        return f"{cls}(_borrowed={expr}, _from_{snake(receiver)}=self._o)"

    def _array_element(self, base, depth, expr, what):
        """(Mojo type, raw type, expression) for element `expr` of a C array whose
        elements are `base` with `depth` pointers; handles are received."""
        info = self.ct.get(base, {})
        if info.get("kind") == "handle" and depth == 0:
            cls = self._class_of(base, what)
            return cls, base, self.received(base, expr, "api")
        if base == "char" and depth == 1:
            return "String", "CChars", f"to_string({expr})"
        if base in INT_IN and depth == 0:
            return "Int", RAW_SCALAR[base], f"Int({expr})"
        if base in OTHER_SCALARS and depth == 0:
            return OTHER_SCALARS[base], RAW_SCALAR[base], expr
        raise Unsupported(f"{what} of `{base}{'*' * depth}`")

    def _is_out_array(self, p):
        """Whether out-parameter `p` receives an array (`T**`, `const char***`)."""
        base, depth, _ = gen_raw._split(p["type"])
        return depth == (3 if base == "char" else 2)

    def _dict_result(self, cname, arrays, count, prep, args, post):
        """A `Dict` from a count and two out-arrays that are a C++ map's keys and values."""
        maps = [m["result"] for m in self.maps(cname) if m["result"]]
        if len(arrays) != 2 or len(maps) != 1:
            raise Unsupported(f"returns {len(arrays)} arrays, and {len(maps)} C++ maps")
        types, exprs, handles = [], [], []
        for p in arrays:
            base, depth, _ = gen_raw._split(p["type"])
            mojo, raw, expr = self._array_element(base, depth - 2, f"{p['name']}[unsafe_offset=i]", "out-array element")
            prep.append(f"var {p['name']} = null[{raw}]()")
            args[p["_index"]] = f"Pointer(to={p['name']})"
            types.append(mojo)
            exprs.append(expr)
            handles.append(base if self.ct.get(base, {}).get("kind") == "handle" and depth == 2 else None)
        self._check_map(maps[0], types, f"`{cname}`")
        mojo = f"Dict[{types[0]}, {types[1]}]"
        post.append(f"var items = {mojo}(capacity=Int({count['name']}))")
        if not any(handles):
            post += [f"for i in range(Int({count['name']})):", f"    items[{exprs[0]}] = {exprs[1]}"]
            return mojo, "items^"
        # C exports every reference in both arrays before conversion starts.
        # Adopt the current row before any string decoding can raise. On error,
        # Mojo destroys adopted locals/items; finally releases each pending tail.
        # Separate cursors also cover a fallible expression before adoption.
        locals_ = ("key", "value")
        for local, handle in zip(locals_, handles):
            if handle:
                post.append(f"var received_{local} = 0")
        post += ["try:", f"    for i in range(Int({count['name']})):"]
        for local, expr, handle in zip(locals_, exprs, handles):
            if handle:
                post += [f"        var {local} = {expr}", f"        received_{local} += 1"]
        for local, expr, handle in zip(locals_, exprs, handles):
            if not handle:
                post.append(f"        var {local} = {expr}")
        post += ["        items[key^] = value^", "finally:"]
        for local, handle, p in zip(locals_, handles, arrays):
            if handle:
                _, release = self.lifecycle(self._class_of(handle, "out-array element"))
                post += [f"    for i in range(received_{local}, Int({count['name']})):",
                         f"        api[].{release}({p['name']}[unsafe_offset=i])"]
        return mojo, "items^"

    def results(self, cname, owner_receiver, cls_of_receiver=None):
        """(prep lines, C argument per out-parameter, post lines, [(Mojo type, expression)])."""
        f = self.cf[cname]
        _, outs, count = self.shape(cname)
        prep, args, post, values = [], {}, [], []
        arrays = [p for p in outs if self._is_out_array(p)]
        if count is not None:
            prep.append(f"var {count['name']} = UInt(0)")
            args[count["_index"]] = f"Pointer(to={count['name']})"
        if arrays:
            if count is None:
                raise Unsupported(f"out-array `{arrays[0]['name']}` has no count")
            # A C++ map: Python returns a dict, C fills a key and a value array.
            values.append(self._dict_result(cname, arrays, count, prep, args, post))
        for p in outs:
            if p in arrays:
                continue
            n = p["name"]
            base, depth, _ = gen_raw._split(p["type"])
            info = self.ct.get(base, {})
            if base == "char" and depth == 2 and n == "error_msg":
                prep.append(f"var {n} = null[Int8]()")
                post += [f"if not is_null({n}):", f'    raise Error("cvc5: " + to_string({n}))']
            elif base == "char" and depth == 2:
                prep.append(f"var {n} = null[Int8]()")
                values.append(("String", f"to_string({n})"))
            elif info.get("kind") == "handle" and depth == 1:
                prep.append(f"var {n} = {base}(null[NoneType]())")
                values.append((self._class_of(base, "out-parameter"), self.received(base, n, "api")))
            elif base in RAW_SCALAR and depth == 1:
                prep.append(f"var {n} = {RAW_SCALAR[base]}(0)")
                values.append(("Int" if base in INT_IN else OTHER_SCALARS[base], f"Int({n})" if base in INT_IN else n))
            else:
                raise Unsupported(f"out-parameter `{n}` of type `{p['type']}`")
            args[p["_index"]] = f"Pointer(to={n})"
        base, depth, _ = gen_raw._split(f["returns"])
        info = self.ct.get(base, {})
        r = result_name(f)
        if base == "void" and depth == 0:
            pass
        elif count is not None and depth >= 1:
            if arrays:
                raise Unsupported("returns an array and fills others")
            mojo, _, expr = self._array_element(base, depth - 1, f"{r}[unsafe_offset=i]", "returned array")
            if mojo == "String":
                values.append(("List[String]", f"to_strings({r}, {count['name']})"))
            else:
                post += _list_result(mojo, f"Int({count['name']})", expr)
                values.append((f"List[{mojo}]", "items^"))
        elif count is None and depth == 1 and info.get("kind") == "handle" and self._list_size(cname):
            cls = self._class_of(base, "result element")
            post += _list_result(cls, self._list_size(cname), self.received(base, f'{r}[unsafe_offset=i]', 'api'))
            values.append((f"List[{cls}]", "items^"))
        elif info.get("kind") == "handle" and depth == 0:
            values.append((self._class_of(base, "result"), self.received(base, r, "api")))
        elif info.get("kind") == "opaque" and depth == 1:
            cls = self._class_of(base, "result")
            if not owner_receiver:
                raise Unsupported(f"returns the pointer-owned `{cls}` from a handle")
            values.append((cls, self.borrowed(base, r, cls_of_receiver)))
        elif info.get("kind") == "enum" and depth == 0:
            values.append((info["enum"], r))
        elif base == "bool" and depth == 0:
            values.append(("Bool", r))
        elif base in INT_IN and depth == 0:
            values.append(("Int", f"Int({r})"))
        elif base in OTHER_SCALARS and depth == 0:
            values.append((OTHER_SCALARS[base], r))
        elif base == "char" and depth == 1:
            values.append(("String", f"to_string({r})"))
        elif base == "char32_t" and depth == 1:
            raise Unsupported("zero-terminated UTF-32 result needs a length-preserving manual conversion")
        else:
            raise Unsupported(f"result of type `{f['returns']}`")
        if count is not None and not arrays and not (depth >= 1 and base != "void"):
            raise Unsupported("has an array count but no array")
        return prep, args, post, values

    def _list_size(self, cname):
        """For a C function that returns one element per input array element:
        the expression for that length, else None."""
        groups, _, _ = self.shape(cname)
        lists = [g for g in groups if g[0] == "lists"]
        if len(lists) != 1:
            return None
        return f"len({gen_raw._identifier(lists[0][1][0]['name'], 0)}_c)"

    # -- overloads -------------------------------------------------------

    def overloads(self, cls, method, receiver=None):
        """Every Mojo overload of `cls.method`, and the reasons for C functions left out."""
        m = self.classes[cls]["info"]["methods"][method]
        py = python_params(m["params"])
        out, reasons, seen = [], [], set()
        for cname in m["binding"]["c"]:
            if cname not in self.raw_bound:
                reasons.append(f"`{cname}` {self.raw_excluded.get(cname, 'is not in the raw layer')}")
                continue
            if self.cf[cname].get("deprecated") and len(m["binding"]["c"]) > 1:
                continue
            try:
                for o in self._overload(cls, method, cname, py, receiver):
                    key = (o.get("alias_name"), tuple(p.mojo + ("*" if p.variadic else "")
                                                    for p in o["params"] if p.default is None))
                    if key not in seen:
                        seen.add(key)
                        out.append(o)
            except Unsupported as e:
                reasons.append(f"`{cname}`: {e}")
        if not out:
            raise Unsupported("; ".join(reasons) or "no C function")
        return out, reasons

    def _overload(self, cls, method, cname, py, receiver):
        owner = self.classes[cls]["owner"]
        params = self.input_params(cname)
        prep, out_args, post, values = self.results(cname, owner, cls)
        # Python names: the parameter Python passes as that argument of the
        # C++ call (`cpp_args`), else by position; a compound name such as
        # `kind_or_op` keeps the C name. Past a Python `*args` that is not the
        # last list, C names are kept.
        fed = self._fed_by(cls, method, cname, len(params))
        by_name = {entry[0]: entry for entry in py}
        variadic_at = None
        for i, param in enumerate(params):
            entry = by_name.get(fed[i]) if fed[i] else (py[i] if i < len(py) else None)
            if entry is None:
                continue
            name, default, star = entry
            if star:
                if param.mojo.startswith("List[") and i == len(params) - 1:
                    param.rename(gen_raw._identifier(name, i))
                    variadic_at = i
                break
            if "_or_" not in name:
                param.rename(gen_raw._identifier(name, i))
            if default == "None" and param.nullable[0]:
                self._make_optional(param)
            elif default is not None:
                if default == "None" and param.mojo == "Bool":
                    default = self.snap["none_bool_defaults"].get(f"{cls}.{method}", default)
                param.default = self._default(default, param.mojo)
        for name, default, star in py[len(params):]:
            if default is None and not star:
                raise Unsupported(f"Python parameter `{name}` has no C counterpart")
        for param in params:
            for old, new in param.renames:
                post = [re.sub(rf"\b{re.escape(old)}_c\b", f"{new}_c", s) for s in post]
        # Defaults must be trailing.
        seen_required = False
        for param in reversed(params):
            if param.default is None:
                seen_required = True
            elif seen_required:
                param.default = None
        number = self.classes[cls]["info"]["methods"][method].get("number")
        if number:
            # Python parses cvc5's decimal text into an `int` or a `Fraction`.
            if len(values) != 1 or values[0][0] != "String":
                raise Unsupported(f"Python returns a `{number}`, but `{cname}` returns no string")
            values = [(NUMBERS[number], f"{NUMBERS[number]}({values[0][1]})")]
        result = None
        if len(values) == 1:
            result = values[0]
        elif values:
            result = (f"Tuple[{', '.join(t for t, _ in values)}]", f"({', '.join(e for _, e in values)})")
        base = {"cls": cls, "method": method, "cname": cname, "params": params, "prep": prep,
                "out_args": out_args, "post": post, "result": result, "receiver": receiver,
                "alias_name": self.classes[cls]["info"]["methods"][method]["binding"].get("private", {}).get(cname)}
        found = [base]
        if variadic_at is not None:
            v = dict(base)
            v["params"] = [Param(p.name, p.mojo[5:-1] if i == variadic_at else p.mojo, p.c_args, p.prep, p.keep,
                                 p.default, i == variadic_at, p.c_index) for i, p in enumerate(params)]
            found.insert(0, v)
            # Preserve literals in heterogeneous variadic index calls, where
            # choosing Int for the pack would narrow before our range checks.
            p = v["params"][variadic_at]
            if p.mojo == "Int" and any("to_c_uint32(" in line for line in p.prep):
                p.mojo = "Integer"
        # Literal-specialized overloads preserve the ordinary Int fast path.
        # Every combination is needed: a call can mix literals and dynamic Ints.
        for original in list(found):
            bounded = [i for i, p in enumerate(original["params"])
                       if p.mojo == "Int" and not p.variadic and any("to_c_" in arg for arg in p.c_args)]
            for count in range(1, len(bounded) + 1):
                for selected in combinations(bounded, count):
                    variant = dict(original)
                    variant["params"] = [copy(p) for p in original["params"]]
                    for i in selected:
                        p = variant["params"][i]
                        p.mojo, p.default = "IntLiteral", None
                        p.c_args = [re.sub(rf"\b{re.escape(p.name)}\b", f"checked_int_literal({p.name})", arg)
                                    for arg in p.c_args]
                    # A selected optional literal becomes required; earlier
                    # defaults cannot precede it in a Mojo signature.
                    for p in variant["params"][:max(selected)]:
                        p.default = None
                    found.append(variant)
        return found

    def _fed_by(self, cls, method, cname, count):
        """For each of the `count` arguments of `cname`, the Python parameter
        that Python's C++ call of the same method and arity reads there alone,
        or None; the call sites must agree."""
        sites = [site for call in self.cf[cname]["cpp_calls"]
                 for site in self.classes[cls]["info"]["methods"][method].get("cpp_args", {}).get(call, [])
                 if len(site) == count]
        fed = [None] * count
        for i in range(count):
            names = {tuple(site[i]) for site in sites}
            if len(names) == 1 and len(next(iter(names))) == 1:
                fed[i] = next(iter(names))[0]
        return fed

    def _default(self, value, mojo):
        if value in ("True", "False") and mojo == "Bool":
            return value
        if value == "None" and mojo == "Bool":
            raise Unsupported("a None Boolean default needs an explicit binding policy")
        if re.fullmatch(r"-?\d+", value) and mojo in ("Int", "UInt64"):
            return value
        if re.fullmatch(r"(\w+)\.\w+", value) and value.split(".")[0] == mojo:
            return value
        if re.fullmatch(r"'[^'\\]*'|\"[^\"\\]*\"", value) and mojo == "String":
            return '"' + value[1:-1] + '"'
        if value in ("{}", "dict()") and mojo.startswith("Dict["):
            return f"{mojo}()"
        return None

    # -- classification ----------------------------------------------------

    def classify(self):
        """{class: {method: (overloads or None, reason or None)}} for every mirrored method."""
        out = {}
        for cls in self.classes:
            methods = {}
            for name, m in self.classes[cls]["info"]["methods"].items():
                b = m["binding"]
                if b["status"] in NOT_MIRRORED:
                    continue
                try:
                    methods[name] = (self.method(cls, name), None)
                except Unsupported as e:
                    methods[name] = (None, str(e))
            out[cls] = methods
        return out

    def method(self, cls, name):
        b = self.classes[cls]["info"]["methods"][name]["binding"]
        status = b["status"]
        hand = [{"kind": "manual", "body": body} for n, body in self.manual.get(cls, {}).get("methods", []) if n == name]
        if status == "manual":
            if not hand:
                raise Unsupported("hand-written, not yet written" + (f": {b['note']}" if b.get("note") else ""))
            return hand
        if status == "rule" and not b.get("c"):
            return [{"kind": "null-check"}]
        if name == "__iter__":
            return [self._iterate(cls, b["c"])]
        if b.get("kind"):
            return [self._mk_term(cls, name, b["kind"])]
        if status == "alias":
            target_cls, target = b["to"].split(".", 1)
            getter = self._getter(cls, target_cls)
            ovs, _ = self.overloads(target_cls, target, receiver=getter)
            return ovs + hand
        ovs, _ = self.overloads(cls, name)
        return ovs + hand  # hand-written overloads added to the generated ones

    def owner_tm(self, cls, h, parents):
        """Term manager for owned or borrowed state: itself or its first parent."""
        if self.classes[cls]["ctype"] == self.tm_ctype:
            return h
        if parents:
            return parents[0]
        raise SystemExit(f"{cls}: no parent gives the term manager")

    def owner_guards(self, cls, params):
        """Keep a constructor's supplied owners in one native term-manager graph.

        The state remembers its first required owner's manager. Additional
        owners, including optional ones, must agree before native allocation.
        Native identity permits copied and borrowed wrappers of the same owner.
        """
        required = [p for p in params if p.mojo in self.owners]
        if not required:
            return []  # The term manager constructor itself has no parents.
        primary = required[0]
        out = []
        for p in params:
            optional = re.fullmatch(r"Optional\[(\w+)\]", p.mojo)
            owner = optional[1] if optional else p.mojo
            if p is primary or owner not in self.owners:
                continue
            value = p.name + (".value()" if optional else "")
            condition = f"{value}._o[].tm.ptr != {primary.name}._o[].tm.ptr"
            if optional:
                condition = f"{p.name} and " + condition
            labels = [snake(t).replace("_", " ") for t in (primary.mojo, owner)]
            message = f"cvc5_mojo: {cls} {' and '.join(labels)} must share a term manager"
            out += [f"if {condition}:", f"    raise Error({json.dumps(message)})"]
        return out

    def _iterate(self, cls, cnames):
        """`__iter__` from a count function and a get-by-index function, as the
        C API offers for what Python iterates over."""
        receiver = self.classes[cls]["ctype"] + ("*" if self.classes[cls]["owner"] else "")
        types = lambda n: [p["type"] for p in self.cf[n]["params"]]
        count = [n for n in cnames if self.cf[n]["returns"] == "size_t" and types(n) == [receiver]]
        get = [n for n in cnames if types(n) == [receiver, "size_t"]]
        if len(cnames) != 2 or len(count) != 1 or len(get) != 1:
            raise Unsupported("`__iter__` needs a count function and a get-by-index function")
        for n in cnames:
            if n not in self.raw_bound:
                raise Unsupported(f"`{n}` {self.raw_excluded.get(n, 'is not in the raw layer')}")
        base, depth, _ = gen_raw._split(self.cf[get[0]]["returns"])
        if depth != 0 or self.ct.get(base, {}).get("kind") != "handle":
            raise Unsupported(f"`{get[0]}` does not return a handle")
        return {"kind": "iterate", "count": count[0], "get": get[0], "elem": self._class_of(base, "element")}

    def _mk_term(self, cls, name, kind):
        """A Term method that builds a term of `kind` from the receiver and its arguments."""
        if self.classes[cls]["ctype"] != self.term_ctype:
            raise Unsupported(f"`kind` builds terms, but `{cls}` is not the term class")
        params = []
        for raw in reference._split(self.classes[cls]["info"]["methods"][name]["params"]):
            tokens = raw.replace("not None", "").split()
            if tokens == ["self"]:
                continue
            if len(tokens) != 2 or tokens[0] != cls:
                raise Unsupported(f"`kind` needs `{cls}` arguments, not `{raw}`")
            params.append(Param(gen_raw._identifier(tokens[1], 0), cls, []))
        return {"kind": "mk_term", "term_kind": kind, "params": params, "result": (cls, None)}

    def _getter(self, cls, target_cls):
        """The C function that returns `target_cls`'s object from `cls`'s."""
        src, dst = self.classes[cls]["ctype"] + "*", self.classes[target_cls]["ctype"] + "*"
        found = [n for n, f in self.cf.items() if f["returns"] == dst and [p["type"] for p in f["params"]] == [src]]
        if len(found) != 1:
            raise Unsupported(f"no single C function returns `{dst}` from `{src}`")
        return found[0]


