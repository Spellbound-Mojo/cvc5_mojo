def _section_text(text):
    """A docstring section body as Mojo requires it: capitalized, ending in punctuation."""
    lines = [x.rstrip() for x in text.splitlines()]
    while lines and not lines[-1]:
        lines.pop()
    if not lines:
        return []
    if lines[0][:1].islower():
        lines[0] = lines[0][0].upper() + lines[0][1:]
    if lines[-1][-1] not in ".!?`":
        lines[-1] += "."
    return lines


def _docstring(doc, params, has_result, indent="        "):
    """A Mojo docstring from cvc5's Python docstring.

    Mojo checks docstrings: `Args:` must document every parameter, in order,
    so it appears only when cvc5 documents all of them by the same names.
    """
    parts = docstrings.parse(doc)
    lines = [_sentence(parts["summary"]) or "See cvc5's Python documentation."]
    if parts["body"]:
        lines += [""] + parts["body"].splitlines()
    documented = dict(parts["params"])
    if params and all(p.name in documented and _section_text(documented[p.name]) for p in params):
        lines += ["", "Args:"]
        for p in params:
            text = _section_text(documented[p.name])
            lines.append(f"    {p.name}: {text[0]}")
            lines += [f"        {x}" if x else "" for x in text[1:]]
    returns = _section_text(parts["returns"]) if has_result else []
    if returns:
        lines += ["", "Returns:"] + [f"    {x}" if x else "" for x in returns]
    body = [indent + '"""' + _escape(lines[0])]
    body += [(indent + _escape(x)) if x else "" for x in lines[1:]]
    if len(lines) > 1:
        body.append(indent + '"""')
    else:
        body[0] += '"""'
    return body


def _call(model, o, api):
    """The C call of an overload, its arguments placed at their C positions."""
    n = len(model.cf[o["cname"]]["params"])
    args = [None] * n
    if o["receiver"] is not None:
        args[0] = o["receiver"]
    elif not o.get("constructor"):
        args[0] = model.receiver_context(o["cls"])[2]
    for p in o["params"]:
        for k, a in zip(p.c_index, p.c_args):
            args[k] = a
    for k, a in o["out_args"].items():
        args[k] = a
    missing = [model.cf[o["cname"]]["params"][k]["name"] for k, a in enumerate(args) if a is None]
    if missing:
        raise SystemExit(f"{o['cname']}: no argument for {missing}")
    return f"{api}[].{o['cname']}(" + ", ".join(args) + ")"


def _overload_lines(model, o, doc, raises=True):
    name = o["method"] if o.get("alias_name") is None else o["alias_name"]
    params = o["params"]
    sig = "    def " + name + "(self" + "".join(", " + p.decl() for p in params) + ")"
    sig += " raises" if raises else ""
    if o["result"]:
        sig += f" -> {o['result'][0]}"
    out = [sig + ":"]
    out += _docstring(doc, params, o["result"] is not None)
    body = ["var api = " + model.receiver_context(o["cls_self"])[0]]
    null_result = model.classes[o["cls_self"]]["info"]["methods"].get(name, {}).get("null_result")
    if null_result is not None:
        result_type = o["result"][0]
        kind = null_result["kind"]
        if kind == "bool" and result_type == "Bool":
            statement = f"return {null_result['value']}"
        elif kind == "enum" and result_type == null_result["type"]:
            if null_result["name"] not in model.snap["enums"][result_type]:
                raise SystemExit(f"{name}: unknown null enum result")
            statement = f"return {result_type}.{null_result['name']}"
        elif kind == "null" and result_type == null_result["type"]:
            statement = f"return {result_type}()"
        elif kind == "empty-list" and result_type.startswith("List["):
            statement = f"return {result_type}()"
        elif kind == "error":
            statement = f"raise Error({json.dumps(null_result['message'])})"
        elif kind == "unsafe":
            statement = f'raise Error("cvc5_mojo: {o["cls_self"]}.{name} is undefined on a null object")'
        else:
            raise SystemExit(f"{name}: unsupported null result for {result_type}: {null_result}")
        body = ["if is_null(self._h.ptr):", "    " + statement] + body
    elif name == "isNull" and not model.classes[o["cls_self"]]["owner"]:
        # A null object is null; the C API rejects a NULL handle here.
        body = ["if is_null(self._h.ptr):", "    return True"] + body
    for p in params:
        body += p.prep
    body += o["prep"]
    call = _call(model, o, "api")
    local = result_name(model.cf[o["cname"]])
    if model.cf[o["cname"]]["returns"] != "void":
        body.append(f"var {local} = {call}")
    else:
        body.append(call)
    for p in params:
        body += [f"_ = {k}^" for k in p.keep]
    body += o["post"]
    if o["result"]:
        body.append(f"return {o['result'][1]}")
    return out + ["        " + line for line in model.bind_receiver(body, o["cls_self"])]


def emit_class(model, cls, methods):
    c = model.classes[cls]
    info = c["info"]
    ctype = c["ctype"]
    if c["callback"]:
        lines = [f"trait {cls}(Movable, Deinitable):"] + _docstring(info["doc"], [], False, indent="    ")
        for name, (ovs, _) in methods.items():
            lines += [""] + _method_lines(model, cls, name, ovs, info["methods"][name]["doc"])
        return lines
    first, second = model.lifecycle(cls)
    lines = []
    names = {n for n, (ovs, _) in methods.items() if ovs}
    # Copies are implicit, as Python shares objects: a pointer-owned object is
    # shared through an `ArcPointer`, a handle takes a cvc5 reference.
    traits = ["ImplicitlyCopyable", "Movable"]
    if names & {"__str__", "__repr__"}:
        if "toString" in names:
            formatter = methods["__str__" if "__str__" in names else "__repr__"][0][0]
            existing = methods["toString"][0]
            if (len(existing) != 1 or existing[0].get("params") != []
                    or existing[0].get("cname") != formatter.get("cname")
                    or existing[0].get("result", (None,))[0] != "String"):
                raise SystemExit(f"{cls}.toString: collides with the single-pass formatting helper")
        traits.append("Writable")
    if "__lt__" in names:
        traits.append("Comparable")
    elif "__eq__" in names:
        traits.append("Equatable")
    if "__hash__" in names:
        traits.append("Hashable")
    lines += [f"struct {cls}({', '.join(traits)}):"]
    lines += _docstring(info["doc"], [], False, indent="    ")
    lines.append("")
    if c["owner"]:
        state = f"_{cls}State"
        lines += [f"    var _o: ArcPointer[{state}]", ""]
        ctor = {"cls": cls, "cls_self": cls, "method": "__init__", "cname": first, "receiver": None,
                "constructor": True, "prep": [], "out_args": {}, "post": [], "result": None}
        params = model.input_params(first, receiver=False)
        py = python_params(info.get("init", "self"))
        for i, param in enumerate(params):
            if i < len(py):
                name, default, _ = py[i]
                param.rename(gen_raw._identifier(name, i))
                if default == "None" and param.nullable[0]:
                    model._make_optional(param)
        ctor["params"] = params
        call = _call(model, ctor, "api")
        keepers = model.keepers[cls]
        guards = model.owner_guards(cls, params)
        lines += ["    def __init__(out self" + "".join(", " + p.decl() for p in params) + ") raises:",
                  f'        """Create a cvc5 `{ctype}` (C `{first}`).'
                  + (' Supplied owners must share a term manager.' if guards else '') + '"""']
        lines += ["        " + line for line in guards]
        for p in params:
            if p.mojo in model.callback_owners:
                lines.append(f"        {p.name}._o[].callbacks[]._available()")
        lines.append("        var api = c_api()")
        for p in params:
            lines += ["        " + x for x in p.prep]
        lines.append(f"        var h = {call}")
        for p in params:
            lines += ["        " + f"_ = {k}^" for k in p.keep]
        parents = [f"{p.name}._o[].tm" for p in params if p.mojo in model.owners]
        lines.append(f"        self._o = ArcPointer({state}(api, h, True, {model.owner_tm(cls, 'h', parents)}))")
        if cls in model.callback_owners:
            for p in params:
                if p.mojo in model.callback_owners:
                    lines.append(f"        self._o[].callbacks = {p.name}._o[].callbacks")
        for k in keepers:
            tm = model.owner_tm(cls, '_borrowed', [f'_from_{snake(k)}[].tm'])
            lines += ["", f"    def __init__(out self, *, _borrowed: {ctype}, _from_{snake(k)}: ArcPointer[_{k}State]):",
                      f'        """Wrap the object a `{k}` returned; it keeps the `{k}` alive."""',
                      f"        var state = {state}(_from_{snake(k)}[].api, _borrowed, False, {tm})",
                      f"        state.keeper_{snake(k)} = _from_{snake(k)}",
                      "        self._o = ArcPointer(state^)"]
            if cls in model.callback_owners and k in model.callback_owners:
                lines.append(f"        self._o[].callbacks = _from_{snake(k)}[].callbacks")
        lines += ["", f"    def _handle(self) -> {ctype}:", "        return self._o[].h"]
    else:
        mode = model.snap["handles"][ctype]["receive"]
        tm = model.tm_ctype
        anchor_type = f"ArcPointer[_{model.anchors[cls]}State]" if cls in model.anchors else None
        anchor_param = f", anchor: Optional[{anchor_type}] = None" if anchor_type else ""
        lines += ["    var _api: CApiPtr", f"    var _tm: {tm}", f"    var _h: {ctype}"]
        if anchor_type:
            lines.append(f"    var _anchor: Optional[{anchor_type}]")
        lines += ["", f"    def __init__(out self, api: CApiPtr, tm: {tm}, h: {ctype}{anchor_param}):",
                  '        """Wrap a handle cvc5 returned, taking ownership of its reference."""',
                  "        self._api = api", "        self._tm = tm", "        self._h = h"]
        if anchor_type:
            lines.append("        self._anchor = anchor")
        lines += ["",
                  "    @staticmethod",
                  f"    def _received(api: CApiPtr, tm: {tm}, h: {ctype}"
                  + (f", anchor: {anchor_type}" if anchor_type else "") + ") -> Self:",
                  f'        """Receive a handle cvc5 returned (`receive = "{mode}"`)."""']
        lines.append("        return Self(api, tm, h" + (", anchor" if anchor_type else "") + ")")
        if not python_params(info.get("init", "self")):
            # Python's `Sort()` is a null object; in the C API, null is NULL.
            lines += ["", "    def __init__(out self) raises:",
                      f'        """A null object, as Python\'s `{cls}()` creates: `isNull()` is true."""',
                      "        self._api = c_api()", f"        self._tm = {tm}(null[NoneType]())",
                      f"        self._h = {ctype}(null[NoneType]())"]
            if anchor_type:
                lines.append("        self._anchor = None")
        lines += ["", "    def __init__(out self, *, copy: Self):", "        self._api = copy._api",
                  "        self._tm = copy._tm"]
        if anchor_type:
            lines.append("        self._anchor = copy._anchor")
        lines += [
                  "        try:", f"            self._h = copy._h if is_null(copy._h.ptr) else copy._api[].{first}(copy._h)",
                  "        except e:", "            abort(String(e))", "",
                  "    def __deinit__(deinit self):", "        if is_null(self._h.ptr):", "            return",
                  "        try:", f"            self._api[].{second}(self._h)", "        except e:",
                  "            abort(String(e))"]
        if anchor_type:
            lines += ["        _ = self._anchor^  # Release the native handle before its owner."]
    for name, (ovs, _) in methods.items():
        if not ovs:
            continue
        doc = info["methods"][name]["doc"]
        lines.append("")
        lines += _method_lines(model, cls, name, ovs, doc)
    for name, body in model.manual.get(cls, {}).get("methods", []):
        if _is_private(name):
            lines += [""] + body
    for name, info in model.snap.get("extensions", {}).get(cls, {}).items():
        oracle = model.snap["callbacks"]["oracle"]
        if oracle["function"] in info["binding"]["c"]:
            callback = [p for p in model.cf[oracle["function"]]["params"] if p.get("callback")]
            if (not oracle["retained_state"] or oracle["result"] != "borrow"
                    or oracle["type_error"] != "LogicException" or oracle["arguments"] != model.term_ctype
                    or model.snap["handles"][model.term_ctype]["receive"] != "own"
                    or len(callback) != 1 or gen_raw.callback_type(callback[0], model.ct)
                    != 'def(UInt, Pointer[Cvc5Term, MutUntrackedOrigin], Pointer[NoneType, MutUntrackedOrigin]) thin abi("C") -> Ptr'):
                raise SystemExit("oracle callback ABI, receipt or recoverable error protocol changed; review bridge")
        hand = [{"kind": "manual", "body": body} for n, body in model.manual.get(cls, {}).get("methods", []) if n == name]
        if not hand:
            raise SystemExit(f"{cls}.{name}: C extension has no implementation")
        lines += [""] + _method_lines(model, cls, name, hand, info["doc"])
    if c["owner"]:
        lines += [""] + emit_state(model, cls)
    return lines


def emit_state(model, cls):
    """The state a pointer-owned class shares between its copies."""
    ctype = model.classes[cls]["ctype"]
    _, delete = model.lifecycle(cls)
    keepers = model.keepers[cls]
    lines = ["", f"struct _{cls}State(Movable):",
             f'    """The cvc5 `{ctype}` of a `{cls}`, shared by its copies.',
             "",
             "    An owned object is deleted with the last copy; a borrowed one instead",
             "    keeps the object that returned it alive.",
             '    """', "", "    var api: CApiPtr", f"    var h: {ctype}", "    var owned: Bool",
             f"    var tm: {model.tm_ctype}"]
    lines += [f"    var keeper_{snake(k)}: Optional[ArcPointer[_{k}State]]" for k in keepers]
    if cls in model.callback_owners:
        lines.append("    var callbacks: ArcPointer[_CallbackRegistry]")
    lines += ["", f"    def __init__(out self, api: CApiPtr, h: {ctype}, owned: Bool, tm: {model.tm_ctype}):",
              "        self.api = api", "        self.h = h", "        self.owned = owned", "        self.tm = tm"]
    lines += [f"        self.keeper_{snake(k)} = None" for k in keepers]
    if cls in model.callback_owners:
        lines.append("        self.callbacks = ArcPointer(_CallbackRegistry())")
    lines += ["", "    def __deinit__(deinit self):", "        if not self.owned:", "            return",
              "        try:", f"            self.api[].{delete}(self.h)", "        except e:", "            abort(String(e))"]
    if cls in model.callback_owners:
        lines.append("        _ = self.callbacks^  # Native deletion may still use the callbacks.")
    return lines


def _nonraising(model, cls, o, op):
    """The body of a dunder Mojo requires to be non-raising."""
    api = "self._api"
    call = f"{api}[].{o['cname']}(self._h, other._h)"
    if op == "eq":
        expr = call
    elif op == "ne":
        expr = call if o["cname"].endswith("is_disequal") else f"not {call}"
    else:
        expr = f"{call} {COMPARISONS[op]} 0"
    return ["        try:", f"            return {expr}", "        except e:", "            abort(String(e))"]


def _manual_lines(model, cls, name, ovs, doc):
    """Hand-written overloads, with cvc5's docstring after each signature."""
    out = []
    for o in ovs:
        body = o["body"]
        k = _signature_end(body)
        if k + 1 < len(body) and body[k + 1].strip().startswith('"""'):
            raise SystemExit(f"{model.manual[cls]['path']}: {cls}.{name} has a docstring; cvc5's is added")
        sig = " ".join(x.strip() for x in body[: k + 1] if not x.strip().startswith("@"))
        params = [Param(n, None, []) for n in _signature_params(sig)]
        out += ([""] if out else []) + body[: k + 1] + _docstring(doc, params, "->" in sig) + body[k + 1 :]
    return out


def _method_lines_unchecked(model, cls, name, ovs, doc):
    hand = [o for o in ovs if o.get("kind") == "manual"]
    if hand and len(hand) < len(ovs):
        generated = [o for o in ovs if o.get("kind") != "manual"]
        return _method_lines_unchecked(model, cls, name, generated, doc) + [""] + _manual_lines(model, cls, name, hand, doc)
    if hand:
        return _manual_lines(model, cls, name, ovs, doc)
    if ovs[0].get("kind") == "iterate":
        o = ovs[0]
        api, _, h = model.receiver_context(cls)
        out = [f"    def __iter__(self) raises -> OwnedIterator[{o['elem']}]:"]
        out += _docstring(doc, [], True)
        out += [f"        var api = {api}", f"        var size = Int(api[].{o['count']}({h}))"]
        received = model.received(model.classes[o['elem']]['ctype'], f"api[].{o['get']}({h}, UInt(i))", "api")
        out += ["        " + line for line in model.bind_receiver(_list_result(o['elem'], "size", received), cls)]
        out += ["        return OwnedIterator(items^)"]
        return out
    if ovs[0].get("kind") == "mk_term":
        o = ovs[0]
        params = o["params"]
        local = "operands"
        while local in {p.name for p in params}:
            local += "_"
        out = ["    def " + name + "(self" + "".join(", " + p.decl() for p in params) + f") raises -> {cls}:"]
        out += _docstring(doc, params, True)
        out += [f"        var {local} = List[{model.term_ctype}](capacity={len(params) + 1})",
                f"        {local}.append(self._h)"]
        out += [f"        {local}.append({p.name}._h)" for p in params]
        api, tm, _ = model.receiver_context(cls)
        received = model.received(model.term_ctype, "result", api)
        out += [f"        var result = {api}[].cvc5_mk_term({tm}, Kind.{o['term_kind']}, "
                f"UInt(len({local})), {local}.unsafe_ptr())",
                "        return " + model.bind_receiver([received], cls)[0]]
        return out
    if ovs[0].get("kind") == "null-check":
        return ["    def isNull(self) -> Bool:", '        """Whether this object is null (holds no cvc5 object)."""',
                "        return is_null(self._h.ptr)"]
    o = ovs[0]
    if name in ("__eq__", "__ne__"):
        return [f"    def {name}(self, other: Self) -> Bool:"] + _nonraising(model, cls, o, name[2:4])
    if name in COMPARISONS:
        return [f"    def {name}(self, other: Self) -> Bool:"] + _nonraising(model, cls, o, name)
    if name == "__hash__":
        # Null objects compare equal, so they hash alike; cvc5 rejects NULL here.
        return ["    def __hash__[H: Hasher](self, mut hasher: H):", "        if is_null(self._h.ptr):",
                "            UInt(0).__hash__(hasher)", "            return", "        try:",
                f"            self._api[].{o['cname']}(self._h).__hash__(hasher)", "        except e:",
                "            abort(String(e))"]
    if name in ("__str__", "__repr__"):
        if name == "__repr__" and "__str__" in model.classes[cls]["info"]["methods"]:
            return []
        printing = model.classes[cls]["info"].get("null_printing")
        existing = "toString" in model.classes[cls]["info"]["methods"]
        prefix = []
        if not model.classes[cls]["owner"]:
            if printing is None:
                raise SystemExit(f"{cls}: null formatting is missing from the oracle")
            # Some Python null formatters raise or even crash. Mojo's Writable
            # cannot raise, so those types get an explicit diagnostic marker.
            text = printing.get("text", f"{cls}(null)")
            if existing:
                prefix = ["        if is_null(self._h.ptr):", f"            writer.write({json.dumps(text)})",
                          "            return"]
            else:
                prefix = ["        if is_null(self._h.ptr):", f"            return {json.dumps(text)}"]
        if existing:
            # Preserve the mirrored method's raising/null contract. Writable
            # still handles null locally and aborts on a native error.
            return ["    def write_to(self, mut writer: Some[Writer]):"] + prefix + ["        try:",
                    "            writer.write(self.toString())", "        except e:",
                    "            abort(String(e))"]
        return ["    def toString(self) -> String:",
                '        """Return an owned string using one native formatting call.',
                "",
                "        Unlike Mojo's two-pass `String(value)` construction, this method",
                "        formats a non-null value once. Null text and non-raising error",
                "        behavior match `write_to`; native or UTF-8 errors abort.",
                '        """'] + prefix + ["        try:",
                f"            return to_string(self._api[].{o['cname']}(self._h))", "        except e:",
                "            abort(String(e))", "",
                "    def write_to(self, mut writer: Some[Writer]):",
                "        writer.write(self.toString())"]
    out = []
    for o in ovs:
        o = dict(o, cls_self=cls, alias_name=o.get("alias_name") or (name if o["cls"] != cls else None))
        if o["receiver"] is not None:
            o["receiver"] = f"api[].{o['receiver']}(self._handle())"
        if out:
            out.append("")
        out += _overload_lines(model, o, doc)
    return out


def _method_lines(model, cls, name, ovs, doc):
    """Guard callback hosts at public call boundaries, including command invocation."""
    lines = _method_lines_unchecked(model, cls, name, ovs, doc)
    starts = [i for i, line in enumerate(lines) if line.startswith("    def ")]
    for start in reversed(starts):
        end = next((i for i in range(start + 1, len(lines))
                    if lines[i].startswith(("    def ", "    @"))), len(lines))
        sig_end = start + _signature_end(lines[start:end])
        signature = " ".join(lines[start:sig_end + 1])
        host = "self" if cls in model.callback_owners else next(iter(re.findall(r"\b(\w+): Solver\b", signature)), None)
        if host is None:
            continue
        body = sig_end + 1
        if body < end and lines[body].lstrip().startswith('"""'):
            if lines[body].count('"""') == 1:
                body += 1
                while '"""' not in lines[body]:
                    body += 1
            body += 1
        lines[body:end] = [f"        with _CallbackCall({host}._o[].callbacks):"] + [
            "    " + line if line.strip() else line for line in lines[body:end]]
    return lines


def _callback_wiring(model):
    """Connect methods and state slots from the extracted C++ forwarding code."""
    methods = model.snap["callbacks"]["methods"]
    expected = set(model.classes["Plugin"]["info"]["methods"])
    if (not model.snap["callbacks"]["retained_table"] or set(methods) != expected
            or model.snap["handles"][model.term_ctype]["receive"] != "own"):
        raise SystemExit("plugin callback methods or term receipt changed; review bridge")
    fields = {f["name"]: f for f in model.ct["Cvc5Plugin"]["fields"]}
    lines = ["", "", "def _wire_plugin[P: Plugin](mut table: Cvc5Plugin, state: Ptr):"]
    for method, info in methods.items():
        if not fields.get(info["field"], {}).get("callback"):
            raise SystemExit(f"Plugin.{method}: missing native callback field")
        params = fields[info["field"]]["params"]
        handles = [gen_raw._split(p["type"])[0] for p in params
                   if model.ct.get(gen_raw._split(p["type"])[0], {}).get("kind") == "handle"]
        if handles != info["exports"] or bool(info["state"]) != any(p["type"] == "void*" for p in params):
            raise SystemExit(f"Plugin.{method}: callback exports or state forwarding changed")
        lines.append(f"    table.set_{info['field']}(_plugin_{method}[P])")
        if info["state"]:
            if fields.get(info["state"], {}).get("type") != "void*":
                raise SystemExit(f"Plugin.{method}: callback state is not void*")
            lines.append(f"    table.set_{info['state']}(state)")
    return lines


_GENERATED = {}


def generated(snap):
    """(Model, classification) for a snapshot, computed once per snapshot object."""
    cached = _GENERATED.get(id(snap))
    if cached is None or cached[0] is not snap:  # the entry holds `snap`, so its id is not reused
        model = Model(snap)
        cached = _GENERATED[id(snap)] = (snap, model, model.classify())
    return cached[1], cached[2]


def signatures(model, cls, name, ovs):
    """The Mojo `def` lines of a generated method, exactly as emitted."""
    return [line.strip().removesuffix(":") for line in _method_lines(model, cls, name,
                                                                  [o for o in ovs if not o.get("alias_name")], "")
            if line.startswith("    def ")]


def emit_module(model, cls, methods, version):
    manual = model.manual.get(cls, {})
    body = emit_class(model, cls, methods)
    if manual.get("extra"):
        body += ["", ""] + manual["extra"]
    if model.classes[cls]["callback"]:
        body += _callback_wiring(model)
    text = "\n".join(body)
    code = re.sub(r'"""(.*?)"""', "", text, flags=re.S)  # names in docstrings need no import
    raw_names = ["CApiPtr", "c_api"] + [t for t in model.ct if model.ct[t]["kind"] in ("handle", "opaque", "struct", "c_enum")]
    ffi_names = ["CChars", "c_bytes", "to_string", "to_strings", "null", "is_null", "checked_int_literal",
                 "to_c_int32", "to_c_uint32", "to_c_size", "OwnedIterator", "write_python_repr"]
    enums = [i["enum"] for i in model.ct.values() if i["kind"] == "enum"]
    used = lambda names: [n for n in names if re.search(rf"\b{re.escape(n)}\b", code)]
    head = [f"{MARKER} from the cvc5 {version} API snapshot. Do not edit.",
            "# Regenerate with `pixi run --locked generate`.",
            f'"""The cvc5 `{cls}` class, mirroring `cvc5.{cls}` of the Python base API."""', ""]
    std = []
    if "ArcPointer" in code:
        std.append("from std.memory import ArcPointer")
    if "abort(" in code:
        std.append("from std.os import abort")
    if "Hasher" in code:
        std.append("from std.hashlib import Hasher")
    std += [line for line in manual.get("imports", []) if line not in std]
    head += std + ([""] if std else [])
    if cls != "Plugin":
        internals = used(["_CallbackRegistry", "_CallbackCall", "_CallbackRegistration", "_PluginState", "_wire_plugin"])
        if internals:
            head.append("from .plugin import " + ", ".join(internals))
    for module, names in (("apn_mojo", used(list(NUMBERS.values()))), ("._c.ffi", used(ffi_names)),
                          ("._c.raw", used(raw_names)), (".enums", used(enums))):
        if names:
            head.append(f"from {module} import {', '.join(names)}")
    for other in sorted(model.classes):
        names = [n for n in (other, f"_{other}State") if other != cls and re.search(rf"\b{n}\b", code)]
        if names:
            head.append(f"from .{model.classes[other]['module']} import {', '.join(names)}")
    return "\n".join(head + ["", ""] + body) + "\n"


def emit_init(model, version):
    enums = [i["enum"] for i in model.ct.values() if i["kind"] == "enum"]
    lines = [f"{MARKER} from the cvc5 {version} API snapshot. Do not edit.",
             "# Regenerate with `pixi run --locked generate`.",
             '"""Mojo bindings for the cvc5 SMT solver, mirroring the cvc5 Python base API."""', ""]
    for cls in sorted(model.classes, key=lambda c: model.classes[c]["module"]):
        names = [cls] + model.manual.get(cls, {}).get("public", [])
        lines.append(f"from .{model.classes[cls]['module']} import {', '.join(names)}")
    lines.append("from .enums import (")
    lines += [f"    {e}," for e in enums]
    lines.append(")")
    return "\n".join(lines) + "\n"


def main():
    from . import generation_policy
    snap = json.loads(config.SNAPSHOT_FILE.read_text(encoding="utf-8"))
    model = Model(snap)
    version = snap["cvc5"]["version"]
    table = model.classify()
    generation_policy.check(generation_policy.missing_methods(table), snap["generation"]["missing_methods"], "base API")
    written = {}
    for cls, methods in table.items():
        written[config.PACKAGE_DIR / f"{model.classes[cls]['module']}.mojo"] = emit_module(model, cls, methods, version)
    written[config.PACKAGE_DIR / "__init__.mojo"] = emit_init(model, version)
    for path in config.PACKAGE_DIR.glob("*.mojo"):
        if path not in written and path.read_text(encoding="utf-8").startswith(MARKER):
            path.unlink()
    for path, text in written.items():
        path.write_text(text, encoding="utf-8")
    generated = sum(1 for ms in table.values() for ovs, _ in ms.values() if ovs)
    hand = sum(1 for ms in table.values() for ovs, _ in ms.values() if ovs and all(o.get("kind") == "manual" for o in ovs))
    total = sum(len(ms) for ms in table.values())
    print(f"wrote {len(table)} classes: {generated} of {total} mirrored methods generated, {hand} of them hand-written")
    for cls, ms in table.items():
        for name, (ovs, reason) in ms.items():
            if not ovs:
                print(f"  not generated: {cls}.{name}: {reason}")


if __name__ == "__main__":
    main()
