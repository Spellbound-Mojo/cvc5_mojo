# C integer types: the conversion of an `Int` argument, and the C type name
# used for result conversions.
INT_IN = {
    "int": "to_c_int32({})",
    "int32_t": "to_c_int32({})",
    "uint32_t": "to_c_uint32({})",
    "int64_t": "Int64({})",
    "size_t": "to_c_size({})",
}
OTHER_SCALARS = {"uint64_t": "UInt64", "double": "Float64"}
# C scalar types as the raw layer spells them, for out-parameter variables.
RAW_SCALAR = {base: mojo for base, (mojo, _, _) in gen_raw.SCALARS.items()}

# Python's arbitrary-precision numbers, and the apn_mojo types that mirror them.
