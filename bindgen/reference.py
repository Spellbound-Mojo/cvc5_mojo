"""Render API reference Markdown from the snapshot (api/cvc5-api.json).

Each Python class of the cvc5 base API gets one section: its description, a
summary table, then every mirrored method with its current Mojo declarations,
upstream Python signature, documentation (converted from cvc5's docstrings),
and its binding to the C
API. Methods that are not mirrored are listed at the end. Generated methods
show their Mojo signatures as bindgen.gen_api emits them; the others show
the Python signature and why they are not generated yet.
"""

from . import docstrings

NOT_MIRRORED = ("skip", "deprecated")


def _split(text):
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
            continue
        depth += ch in "([{"
        depth -= ch in ")]}"
        cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def signature(cls, name, params):
    """A Python signature from Cython parameters: `name: Type = default`."""
    shown = []
    for p in _split(params):
        p = p.replace("not None", "").strip()
        default = ""
        if "=" in p:
            p, default = (x.strip() for x in p.split("=", 1))
        tokens = p.split()
        if tokens == ["self"]:
            continue
        arg = f"{tokens[-1]}: {' '.join(tokens[:-1])}" if len(tokens) > 1 else tokens[0]
        shown.append(arg + (f" = {default}" if default else ""))
    return f"{cls}.{name}({', '.join(shown)})"


def anchor(cls, method):
    """The HTML id of a method entry. Underscores are dropped: Markdown would
    read the ones in `__eq__` as emphasis, even inside an attribute list."""
    return f"{cls}.{method.replace('_', '')}"


def _escape(text):
    return text.replace("_", "\\_")


def _codes(names):
    return ", ".join(f"`{n}`" for n in names)


def binding_text(binding, link):
    status = binding["status"]
    note = f" {binding['note']}." if binding.get("note") else ""
    if status == "auto":
        return f"Generated from {_codes(binding['c'])}."
    if status == "overloaded":
        return f"Generated as overloads from {_codes(binding['c'])}."
    if status == "rule":
        if binding.get("c"):
            return f"Generated by a rule from {_codes(binding['c'])}."
        return "Generated by a rule: a check for a NULL handle, which is how the C API represents a null object."
    if status == "alias":
        cls, method = binding["to"].split(".", 1)
        return f"Same as [`{binding['to']}`]({link(cls, method)})."
    if status == "override":
        return f"Bound to {_codes(binding['c'])} by `bindgen/overrides.toml`.{note}"
    if status == "manual":
        return f"Hand-written using {_codes(binding['c'])}.{note}"
    if status == "skip":
        return f"Not mirrored: {binding['reason']}"
    if status == "deprecated":
        return "Not mirrored: deprecated in cvc5."
    return "Unresolved: no binding yet."


def _summary(doc):
    parts = docstrings.parse(doc)
    text = parts["summary"] or (f"Returns {parts['returns'][:1].lower()}{parts['returns'][1:]}" if parts["returns"] else "")
    return docstrings.short(" ".join(text.split()))


def class_markdown(cls, snap, link, generated=None):
    """One class: description, summary table, then every mirrored method.

    `link(cls, method)` returns the URL of a method's entry, which may be on
    another page. `generated` is `gen_api.generated(snap)`, computed when
    omitted.
    """
    from . import gen_api  # gen_api imports this module

    model, table = generated or gen_api.generated(snap)
    status = table.get(cls, {})
    info = snap["python"][cls]
    methods = info["methods"]
    mirrored = {n: m for n, m in methods.items() if m["binding"]["status"] not in NOT_MIRRORED}
    done = {n for n, (ovs, _) in status.items() if ovs}

    out = [f"## {cls} {{ #{cls} .api-name }}", "", docstrings.markdown(info["doc"]), ""]
    if mirrored:
        out += [f"{len(done & set(mirrored))} of the {len(mirrored)} mirrored methods of `{cls}` are generated."
                + (" Each of the others says why it is not generated." if done & set(mirrored) != set(mirrored)
                   else ""), ""]
        out += ["| Method | Summary | Binding | Mojo |", "|---|---|---|---|"]
    for name, m in mirrored.items():
        mark = "✓" if name in done else "—"
        out.append(f"| [`{name}`](#{anchor(cls, name)}) | {_summary(m['doc'])} | {m['binding']['status']} | {mark} |")
    out.append("")
    for name, m in mirrored.items():
        ovs, reason = status.get(name, (None, "the class is not generated"))
        if ovs:
            code = ["**Mojo declaration:**", "", "```mojo"] + gen_api.signatures(model, cls, name, ovs) + ["```"]
            note = ""
        else:
            code = ["```text", signature(cls, name, m["params"]), "```"]
            note = f" **Not generated**: {reason}."
        if ovs:
            code += ["", "**Upstream Python signature**:", "", "```text",
                     signature(cls, name, m["params"]), "```"]
            if name in ("__str__", "__repr__"):
                code += ["", "Mojo uses the `Writable` protocol here: call `String(value)`, `repr(value)`, or `print(value)`."]
        out += [f"### {cls}.{_escape(name)} {{ #{anchor(cls, name)} .api-name }}", "",
                '<div class="api-signature" markdown="1">', ""] + code + ["", "</div>", "",
                docstrings.markdown(m["doc"]) if m["doc"] else "", "",
                f"**Binding**: {binding_text(m['binding'], link)}{note}", ""]
    hidden = {n: m for n, m in methods.items() if m["binding"]["status"] in NOT_MIRRORED}
    if hidden:
        out += [f'<details class="api-overloads" markdown="1"><summary>{len(hidden)} Python '
                f'method{"s" if len(hidden) > 1 else ""} not mirrored</summary>', ""]
        out += [f"- `{n}`: {binding_text(m['binding'], link)}" for n, m in hidden.items()]
        out += ["", "</details>", ""]
    extensions = snap.get("extensions", {}).get(cls, {})
    if extensions:
        out += ["### C-only extensions", "", "These methods extend the Python base API with C functionality.", ""]
    for name, m in extensions.items():
        ovs = [{"kind": "manual", "body": body} for n, body in model.manual[cls]["methods"] if n == name]
        out += [f"### {cls}.{name} {{ #{anchor(cls, name)} .api-name }}", "", "```mojo",
                *gen_api.signatures(model, cls, name, ovs), "```", "",
                docstrings.markdown(m["doc"]), "", f"**Binding**: {binding_text(m['binding'], link)}", ""]
    return "\n".join(out)


def enums_markdown(snap):
    """Every enum with its values, collapsed per enum."""
    out = []
    for enum, values in snap["enums"].items():
        out += [f"## {enum} {{ #{enum} .api-name }}", "",
                f"The C enum `Cvc5{enum}`, which Python calls `cvc5.{enum}`. Its members are `comptime` values, "
                f"such as `{enum}.{next(iter(values))}`, and they print as in Python.", "",
                f'<details markdown="1"><summary>{len(values)} values</summary>', "",
                "| Name | Value |", "|---|---:|"]
        out += [f"| `{name}` | {value} |" for name, value in values.items()]
        out += ["", "</details>", ""]
    return "\n".join(out)


def kinds_markdown(snap, names):
    """A selected operator table, with summaries from the pinned headers."""
    out = ["| Kind | Meaning in the pinned release |", "|---|---|"]
    for name in names:
        doc = snap["enum_docs"]["Kind"][name]
        out.append(f"| `Kind.{name}` | {_summary(doc)} |")
    return "\n".join(out) + "\n"


def options_markdown(snap, names=None):
    """Option metadata and help share the snapshot and docstring renderer."""
    options = snap['options']

    def literal(value):
        if value is None:
            return 'No scalar default reported'
        if value == '':
            return '`""` (empty string)'
        return '`' + str(value).replace('|', '&#124;').replace('`', '&#96;') + '`'

    if names is not None:
        out = ['| Option | Value kind | Default | Description |', '|---|---|---|---|']
        for name in names:
            info = options[name]
            summary = _summary(info['declaration'].get('help', '')).replace('|', '&#124;')
            out.append(f"| `{name}` | {literal(info['value_kind'])} | {literal(info['default'])} | {summary} |")
        return '\n'.join(out) + '\n'

    out = []
    groups = sorted({o['module'] for o in options.values()})
    for group in groups:
        out += [f'### {group}', '']
        for name, info in options.items():
            if info['module'] != group:
                continue
            declaration = info['declaration']
            out += [f'#### {name} {{ #option-{name} .api-name }}', '',
                    docstrings.markdown(declaration.get('help', 'No upstream help text.')), '',
                    f"**Value kind:** {literal(info['value_kind'])}. "
                    f"**Default:** {literal(info['default'])}. "
                    f"**Category:** {literal(declaration['category'])}.", '']
            if info['aliases']:
                out += ['**Aliases:** ' + ', '.join(literal(a) for a in info['aliases']) + '.', '']
            for key in ('minimum', 'maximum'):
                if key in info:
                    out += [f'**{key.title()}:** {literal(info[key])}.', '']
            if info.get('modes'):
                mode_docs = {value['name']: value.get('help', '')
                             for values in declaration.get('mode', {}).values() for value in values}
                out += ['| Mode | Upstream description |', '|---|---|']
                for mode in info['modes']:
                    help_text = docstrings.inline(mode_docs.get(mode, '')).replace('|', '&#124;').replace('\n', ' ')
                    out.append(f'| {literal(mode)} | {help_text} |')
                out += ['']
            if info['no_support']:
                out += ['**Reported incompatible features:** ' + ', '.join(literal(n) for n in info['no_support']) + '.', '']
            source = f"https://github.com/cvc5/cvc5/blob/{snap['cvc5']['commit']}/{info['source']}"
            out += [f"[Pinned source declaration]({source})", '']
    return '\n'.join(out)
